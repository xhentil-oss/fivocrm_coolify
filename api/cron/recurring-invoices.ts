import type { VercelRequest, VercelResponse } from '@vercel/node';
import nodemailer from 'nodemailer';
import { buildInvoiceEmail } from '../_invoiceEmail';
import admin, { adminDb as db } from '../_firebaseAdmin';

/**
 * Runs on the 1st of each month at 08:00.
 * For every monthly recurring project, creates a Pending invoice and emails
 * the customer immediately — unless one was already generated this month.
 */
export default async function handler(req: VercelRequest, res: VercelResponse) {
  const cronSecret = process.env.CRON_SECRET;
  if (!cronSecret || req.headers.authorization !== `Bearer ${cronSecret}`) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  const smtpUser = process.env.SMTP_USER;
  const smtpConfigured = !!(smtpUser && process.env.SMTP_PASS);
  const transporter = smtpConfigured
    ? nodemailer.createTransport({
        host: process.env.SMTP_HOST || 'mail.fivoo.net',
        port: Number(process.env.SMTP_PORT) || 465,
        secure: true,
        auth: { user: smtpUser!, pass: process.env.SMTP_PASS },
      })
    : null;

  const now = new Date();
  const currentYear = now.getFullYear();
  const currentMonth = now.getMonth(); // 0-indexed

  // Due date = last day of current month
  const dueDate = new Date(currentYear, currentMonth + 1, 0);

  // Fetch all recurring projects
  const projectsSnap = await db.collection('projects')
    .where('isRecurring', '==', true)
    .get();

  let created = 0;
  let skipped = 0;
  const ops: Promise<any>[] = [];

  for (const projectDoc of projectsSnap.docs) {
    const project = projectDoc.data();

    // Only handle monthly recurring projects (weekly/quarterly handled differently if needed)
    if (project.recurringFrequency !== 'monthly') continue;

    // Duplicate guard: check lastInvoiceGeneratedAt on the project
    if (project.lastInvoiceGeneratedAt) {
      const last: Date = project.lastInvoiceGeneratedAt.toDate
        ? project.lastInvoiceGeneratedAt.toDate()
        : new Date(project.lastInvoiceGeneratedAt);

      if (last.getFullYear() === currentYear && last.getMonth() === currentMonth) {
        skipped++;
        continue;
      }
    }

    const budget = project.budget || 0;
    const monthName = now.toLocaleDateString('sq-AL', { month: 'long', year: 'numeric' });
    const invoiceLabel = `AUTO-${currentYear}-${String(currentMonth + 1).padStart(2, '0')}-${projectDoc.id.slice(0, 6).toUpperCase()}`;

    // Create the invoice as Pending (will email customer immediately)
    const invoiceRef = db.collection('invoices').doc();

    ops.push(
      invoiceRef.set({
        invoiceNumber: invoiceLabel,
        projectId: projectDoc.id,
        customerId: project.customerId || null,
        teamId: project.teamId || null,
        amount: budget,
        subtotal: budget,
        total: budget,
        tax: 0,
        status: 'Pending',
        notes: `Faturë e gjeneruar automatikisht për projektin periodik "${project.name}" — ${monthName}.`,
        dueDate: admin.firestore.Timestamp.fromDate(dueDate),
        isRecurring: true,
        recurringFrequency: 'monthly',
        autoGenerated: true,
        emailSent: false,
        reminderSent: false,
        reminder25Sent: false,
        reminderLastDaySent: false,
        createdByUserId: project.createdByUserId || null,
        createdAt: admin.firestore.Timestamp.now(),
        updatedAt: admin.firestore.Timestamp.now(),
      })
    );

    // Add one line item: the project service
    const itemRef = db.collection('invoiceItems').doc();
    ops.push(
      itemRef.set({
        invoiceId: invoiceRef.id,
        description: `${project.name} — shërbime mujore`,
        quantity: 1,
        unitPrice: budget,
        totalPrice: budget,
        createdAt: admin.firestore.Timestamp.now(),
        updatedAt: admin.firestore.Timestamp.now(),
      })
    );

    // Send initial invoice email to customer
    if (transporter && project.customerId) {
      const customerDoc = await db.collection('customers').doc(project.customerId).get();
      const customer = customerDoc.data();
      if (customer?.email) {
        const { subject, html } = buildInvoiceEmail({
          customerName: customer.name || 'Klient',
          invoiceNumber: invoiceLabel,
          amount: budget,
          dueDate,
          projectName: project.name,
          type: 'initial',
        });
        ops.push(
          transporter.sendMail({
            from: `"FivoCRM" <${smtpUser}>`,
            to: customer.email,
            subject,
            html,
          }).then(() =>
            invoiceRef.update({ emailSent: true, updatedAt: admin.firestore.Timestamp.now() })
          )
        );
      }
    }

    // Mark project so we don't re-generate this month
    ops.push(
      projectDoc.ref.update({
        lastInvoiceGeneratedAt: admin.firestore.Timestamp.now(),
        updatedAt: admin.firestore.Timestamp.now(),
      })
    );

    // In-app notification for the project creator
    if (project.createdByUserId) {
      ops.push(
        db.collection('notifications').add({
          userId: project.createdByUserId,
          type: 'auto_invoice_created',
          title: `🧾 Faturë e re automatike: ${project.name}`,
          message: `Fatura #${invoiceLabel} (${budget.toLocaleString('sq-AL')} L) u gjenerua automatikisht nga projekti periodik "${project.name}". Rishiko dhe dërgo tek klienti.`,
          isRead: false,
          createdAt: admin.firestore.Timestamp.now(),
        })
      );
    }

    created++;
  }

  await Promise.allSettled(ops);

  return res.status(200).json({
    success: true,
    created,
    skipped,
    timestamp: new Date().toISOString(),
  });
}

// Read-only: dump every field of the expenses matching a title, to see HOW a
// duplicate was produced. Usage: node scripts/inspect-expense-title.mjs cpanel
import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';

const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const needle = (process.argv[2] || 'cpanel').toLowerCase();
const toDate = (v) => {
  if (!v) return null;
  const d = v?.toDate ? v.toDate() : new Date(v);
  return d instanceof Date && !isNaN(d.getTime()) ? d : null;
};
const stamp = (v) => {
  const d = toDate(v);
  return d ? d.toISOString().replace('T', ' ').slice(0, 19) : '—';
};

const snap = await db.collection('expenses').get();
const rows = snap.docs
  .filter((d) => (d.data().title || '').toLowerCase().includes(needle))
  .map((d) => ({ id: d.id, ...d.data() }))
  .sort((a, b) => (toDate(a.date || a.createdAt) || 0) - (toDate(b.date || b.createdAt) || 0));

console.log(`\n=== ${rows.length} rreshta që përmbajnë "${needle}" ===\n`);
for (const r of rows) {
  console.log(`id=${r.id}`);
  console.log(`  title="${r.title}"  amount=${r.amount} ${r.currency || 'ALL'}  category=${r.category}`);
  console.log(`  date=${stamp(r.date)}  createdAt=${stamp(r.createdAt)}  updatedAt=${stamp(r.updatedAt)}  paidDate=${stamp(r.paidDate)}`);
  console.log(`  isRecurring=${!!r.isRecurring} freq=${r.recurringFrequency || '—'} next=${stamp(r.nextRecurringDate)} paused=${!!r.isRecurringPaused} end=${stamp(r.recurringEndDate)}`);
  console.log(`  autoGenerated=${!!r.autoGenerated} parentExpenseId=${r.parentExpenseId || '—'} periodKey=${r.periodKey || '—'} lastGeneratedPeriodKey=${r.lastGeneratedPeriodKey || '—'}`);
  console.log(`  status=${r.status} approval=${r.approvalStatus || '—'} createdBy=${r.createdByUserId || '—'} businessId=${r.businessId || '—'} teamId=${r.teamId || '—'}`);
  console.log(`  description=${JSON.stringify(r.description || '')}`);
  console.log('');
}

// Same-second bursts are the fingerprint of a double-submit; same-day-different-
// second bursts point at a repeated manual entry or a re-run import.
const byMinute = new Map();
rows.forEach((r) => {
  const c = toDate(r.createdAt);
  if (!c) return;
  const k = c.toISOString().slice(0, 16);
  byMinute.set(k, (byMinute.get(k) || 0) + 1);
});
console.log('Krijime për minutë:');
[...byMinute.entries()].sort().forEach(([k, n]) => console.log(`  ${k}  ×${n}${n > 1 ? '   ← burst' : ''}`));

process.exit(0);

// Remove duplicate expense rows inside one month, keeping exactly one per
// (title, amount, currency, month).
//
// Keep rule, in order:
//   1. a recurring PARENT is never deleted (it drives the series);
//   2. otherwise the EARLIEST row of the month survives.
//
// Dry-run by default. Pass --apply to actually delete, and --archive to snapshot
// every deleted row into `expenseDeduped` first (recommended — deletes of
// accounting rows must be reversible).
//
// Usage: node scripts/dedupe-expenses.mjs [--apply] [--archive] [--business=<id>]
import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore, FieldValue } from 'firebase-admin/firestore';

const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const APPLY = process.argv.includes('--apply');
const ARCHIVE = process.argv.includes('--archive');
const bizArg = process.argv.find((a) => a.startsWith('--business='));
const onlyBusiness = bizArg ? bizArg.split('=')[1] : null;

const toDate = (v) => {
  if (!v) return null;
  const d = v?.toDate ? v.toDate() : new Date(v);
  return d instanceof Date && !isNaN(d.getTime()) ? d : null;
};
const expDate = (x) => toDate(x.date) || toDate(x.createdAt);
const ym = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
const stamp = (d) => (d ? d.toISOString().slice(0, 10) : '—');

const snap = await db.collection('expenses').get();
let rows = snap.docs.map((d) => ({ id: d.id, ...d.data() }));
if (onlyBusiness) rows = rows.filter((r) => r.businessId === onlyBusiness);

const groups = new Map();
for (const r of rows) {
  if (r.approvalStatus === 'Rejected') continue;   // already neutral in every total
  const d = expDate(r);
  if (!d) continue;
  const title = (r.title || '').trim().toLowerCase().replace(/\s+/g, ' ');
  const amount = Number(r.amount) || 0;
  if (!title || amount <= 0) continue;
  const key = [r.businessId || '—', title, amount, r.currency || 'ALL', ym(d)].join('|');
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(r);
}

const toDelete = [];
let waste = 0;
for (const [key, list] of groups) {
  if (list.length < 2) continue;
  const sorted = [...list].sort((a, b) => (expDate(a) - expDate(b)) || String(a.id).localeCompare(String(b.id)));
  // A recurring parent must survive — deleting it would kill the whole series.
  const keeper = sorted.find((r) => r.isRecurring) || sorted[0];
  const [, title, amount, cur, month] = key.split('|');
  console.log(`\n${month} · "${title}" · ${amount} ${cur} · ×${list.length}`);
  for (const r of sorted) {
    const tag = r.isRecurring ? 'PRIND' : r.autoGenerated ? 'auto' : 'i vjetër/manual';
    if (r.id === keeper.id) {
      console.log(`   MBAJ    ${stamp(expDate(r))}  id=${r.id}  [${tag}]`);
    } else {
      console.log(`   FSHI    ${stamp(expDate(r))}  id=${r.id}  [${tag}]`);
      toDelete.push(r);
      waste += Number(amount);
    }
  }
}

console.log(`\n──────────────────────────────────────────────`);
console.log(`Rreshta për fshirje: ${toDelete.length} / ${rows.length}`);
console.log(`Vlera që hiqet nga librat: ${Math.round(waste).toLocaleString()} (monedhat përkatëse)`);
console.log(APPLY ? (ARCHIVE ? 'MODE: APPLY + ARCHIVE' : 'MODE: APPLY (pa arkiv)') : 'MODE: DRY-RUN (asgjë nuk u prek)');

if (!APPLY) process.exit(0);

let done = 0;
for (const r of toDelete) {
  if (ARCHIVE) {
    const { id, ...data } = r;
    await db.collection('expenseDeduped').doc(id).set({
      ...data,
      dedupedAt: FieldValue.serverTimestamp(),
      dedupedBy: 'scripts/dedupe-expenses.mjs',
    });
  }
  await db.collection('expenses').doc(r.id).delete();
  done++;
  if (done % 10 === 0) console.log(`  …${done}/${toDelete.length}`);
}
console.log(`U fshinë ${done} rreshta.${ARCHIVE ? ' Arkivi: expenseDeduped' : ''}`);
process.exit(0);

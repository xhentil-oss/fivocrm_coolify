// Read-only finance coherence audit. Single pass over each collection.
import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';

const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const RATES = { EUR: 100, USD: 92, GBP: 118, ALL: 1, LEK: 1 };
const toAll = (a, c) => (Number(a) || 0) * (RATES[(c || 'ALL').toUpperCase()] ?? 1);
const dt = (v) => (v?.toDate ? v.toDate() : (v ? new Date(v) : null));
const f = (n) => Math.round(n).toLocaleString();
const ACCRUAL = ['Paid', 'Pending', 'Overdue', 'Partial'];
const TERMINAL = ['Cancelled', 'Archived'];

function collected(i) {
  if (['Draft', 'Cancelled'].includes(i.status)) return 0;
  if (i.status === 'Paid') return toAll(i.total ?? i.amount ?? 0, i.currency);
  if (Array.isArray(i.partialPayments) && i.partialPayments.length)
    return i.partialPayments.reduce((s, p) => s + toAll(p.amount ?? 0, i.currency), 0);
  return toAll(i.paidAmount ?? 0, i.currency);
}
const billed = (i) => (ACCRUAL.includes(i.status) ? toAll(i.total ?? i.amount ?? 0, i.currency) : 0);
const monthlyish = (p) => (p.billingType === 'monthly') || (!p.billingType && p.isRecurring);

async function main() {
  const [iS, eS, pS, mS] = await Promise.all([
    db.collection('invoices').get(), db.collection('expenses').get(),
    db.collection('projects').get(), db.collection('teamMembers').get(),
  ]);
  const inv = iS.docs.map(d => ({ id: d.id, ...d.data() }));
  const exp = eS.docs.map(d => ({ id: d.id, ...d.data() }));
  const proj = pS.docs.map(d => ({ id: d.id, ...d.data() }));
  const mem = mS.docs.map(d => d.data());
  const issues = [];

  console.log('═══════ AUDIT FINANCIAR ═══════');
  console.log(`fatura=${inv.length} shpenzime=${exp.length} projekte=${proj.length} anëtarë=${mem.length}\n`);

  // 1) Invoice number collisions
  const byNum = new Map();
  inv.forEach(i => { const n = (i.invoiceNumber || '').trim(); if (n.startsWith('FAT-')) { if (!byNum.has(n)) byNum.set(n, []); byNum.get(n).push(i); } });
  const dupNum = [...byNum.values()].filter(a => a.length > 1);
  console.log(`1. Numra fature të përsëritur: ${dupNum.length ? '⚠ ' + dupNum.length : '✓ 0'}`);
  if (dupNum.length) issues.push('numra fature të përsëritur');

  // 2) Two billing engines on the same project
  const projById = new Map(proj.map(p => [p.id, p]));
  const bothEngines = inv.filter(i => i.isRecurring && !i.autoGenerated && i.projectId
    && projById.get(i.projectId) && projById.get(i.projectId).isRecurring
    && !TERMINAL.includes(projById.get(i.projectId).status));
  console.log(`2. Projekte me të dy motorët e faturimit: ${bothEngines.length ? '⚠ ' + bothEngines.length : '✓ 0'}`);
  bothEngines.forEach(i => console.log(`      ⚠ "${projById.get(i.projectId).name}" ← ${i.invoiceNumber}`));
  if (bothEngines.length) issues.push('dy motorë faturimi');

  // 3) Same project billed twice in one month
  const g = new Map();
  inv.filter(i => i.projectId && i.status !== 'Cancelled').forEach(i => {
    const d = dt(i.invoiceDate) || dt(i.createdAt); if (!d) return;
    const k = `${i.projectId}|${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
    if (!g.has(k)) g.set(k, []); g.get(k).push(i);
  });
  const dblMonth = [...g.entries()].filter(([k, a]) => a.length > 1 && projById.get(k.split('|')[0]) && projById.get(k.split('|')[0]).name !== 'whmcs');
  console.log(`3. Projekt i faturuar 2x në një muaj: ${dblMonth.length ? '⚠ ' + dblMonth.length : '✓ 0'}`);
  dblMonth.forEach(([k, a]) => console.log(`      ⚠ "${projById.get(k.split('|')[0]).name}" ${k.split('|')[1]}: ${a.map(x => x.invoiceNumber).join(', ')}`));
  if (dblMonth.length) issues.push('faturim i dyfishtë brenda muajit');

  // 4) Salary: expense rows vs configured payroll (current month)
  const now = new Date(); const S = new Date(now.getFullYear(), now.getMonth(), 1), E = new Date(now.getFullYear(), now.getMonth() + 1, 0, 23, 59, 59);
  const inNow = (d) => d && d >= S && d <= E;
  const salRows = exp.filter(e => e.category === 'Salary' && e.approvalStatus !== 'Rejected' && inNow(dt(e.date) || dt(e.createdAt)));
  const salTotal = salRows.reduce((s, e) => s + toAll(e.amount, e.currency), 0);
  const payroll = mem.filter(m => m.status === 'Active').reduce((s, m) => s + (Number(m.monthlySalary) || 0), 0);
  const gap = salTotal - payroll;
  console.log(`4. Rroga (muaji aktual): rreshta=${f(salTotal)} vs konfigurim=${f(payroll)} → ${Math.abs(gap) > 1000 ? '⚠ dif ' + f(gap) : '✓ përputhen'}`);
  if (Math.abs(gap) > 1000) issues.push(`rroga: ${f(gap)} jashtë P&L`);

  // 5) Data hygiene
  const noBiz = [...inv, ...exp, ...proj].filter(x => !x.businessId).length;
  const noDept = proj.filter(p => !p.department && !TERMINAL.includes(p.status)).length;
  const noBillingType = proj.filter(p => !p.billingType && !TERMINAL.includes(p.status)).length;
  const invNoProj = inv.filter(i => !i.projectId && ACCRUAL.includes(i.status)).length;
  const noDate = inv.filter(i => !i.invoiceDate).length;
  const zeroSalary = mem.filter(m => m.status === 'Active' && !m.monthlySalary).length;
  console.log(`5. Higjiena e të dhënave:`);
  console.log(`      pa businessId: ${noBiz ? '⚠ ' + noBiz : '✓ 0'}`);
  console.log(`      projekte pa departament: ${noDept ? '⚠ ' + noDept : '✓ 0'}`);
  console.log(`      projekte pa billingType: ${noBillingType ? '⚠ ' + noBillingType : '✓ 0'}`);
  console.log(`      fatura pa projekt (jo-draft): ${invNoProj ? '⚠ ' + invNoProj : '✓ 0'}`);
  console.log(`      fatura pa invoiceDate: ${noDate ? '⚠ ' + noDate : '✓ 0'}`);
  console.log(`      anëtarë aktivë pa pagë: ${zeroSalary ? '⚠ ' + zeroSalary : '✓ 0'}`);

  // 6) Budget-vs-reality per project (the "phantom profit" check)
  const collByProj = new Map();
  inv.forEach(i => { if (!i.projectId) return; collByProj.set(i.projectId, (collByProj.get(i.projectId) || 0) + collected(i)); });
  const live = proj.filter(p => !TERMINAL.includes(p.status) && Number(p.budget) > 0);
  const phantom = live.filter(p => (collByProj.get(p.id) || 0) === 0);
  console.log(`\n6. Projekte aktive me buxhet POR pa asnjë arkëtim: ${phantom.length ? '⚠ ' + phantom.length : '✓ 0'}`);
  phantom.slice(0, 12).forEach(p => console.log(`      "${p.name}" buxhet ${f(toAll(p.budget, p.currency))} ${monthlyish(p) ? '(mujor)' : '(një-herësh)'}`));
  if (phantom.length > 12) console.log(`      … +${phantom.length - 12} të tjera`);

  // 7) Receivables
  const outstanding = inv.reduce((s, i) => s + Math.max(0, billed(i) - collected(i)), 0);
  const overdue = inv.filter(i => i.status === 'Overdue').reduce((s, i) => s + Math.max(0, billed(i) - collected(i)), 0);
  console.log(`\n7. Të pambledhura: ${f(outstanding)} (nga to të vonuara ${f(overdue)})`);

  console.log('\n═══════ PËRFUNDIM ═══════');
  console.log(issues.length ? `⚠ Mospërputhje: ${issues.join(' · ')}` : '✓ Asnjë mospërputhje strukturore');
}
main().then(() => process.exit(0)).catch(e => { console.error(e.code || '', e.details || e.message); process.exit(1); });

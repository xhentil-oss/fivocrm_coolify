// One-off: backfill MISSING monthly recurring expenses for JULY 2026 only.
// For each active monthly recurring parent, if there's no July row for that
// series, create it (mirrors the cron's child fields + periodKey so it won't be
// re-generated). Safe & idempotent: skips series that already have a July entry.
//
//   node scripts/backfill-july-expenses.mjs         (dry-run: shows what it WOULD add)
//   node scripts/backfill-july-expenses.mjs --apply (writes)

import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore, Timestamp } from 'firebase-admin/firestore';

const APPLY = process.argv.includes('--apply');
const YEAR = 2026, MONTH0 = 6; // July = month index 6
const PERIOD_KEY = `${YEAR}-07`;

const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const toDate = (v) => (v?.toDate ? v.toDate() : (v ? new Date(v) : null));
const inJuly = (d) => d && d.getFullYear() === YEAR && d.getMonth() === MONTH0;
const norm = (s) => (s || '').trim().toLowerCase();

async function main() {
  console.log(`[backfill-july] mode=${APPLY ? 'APPLY' : 'DRY-RUN'} period=${PERIOD_KEY}`);
  const snap = await db.collection('expenses').get();
  const all = snap.docs.map(d => ({ id: d.id, ...d.data() }));

  // Existing July rows (non-rejected) — to detect what's already there.
  const julyRows = all.filter(e => e.approvalStatus !== 'Rejected' && inJuly(toDate(e.date) || toDate(e.createdAt)));

  // Active MONTHLY recurring parents.
  const parents = all.filter(e => e.isRecurring && !e.autoGenerated && !e.isRecurringPaused && (e.recurringFrequency || 'monthly') === 'monthly');

  const hasJulyEntry = (p) => julyRows.some(e =>
    e.parentExpenseId === p.id ||
    e.id === p.id ||
    (norm(e.title) === norm(p.title) && Number(e.amount) === Number(p.amount) && norm(e.category) === norm(p.category))
  );

  const missing = parents.filter(p => !hasJulyEntry(p));
  const already = parents.length - missing.length;

  let total = 0, created = 0;
  for (const p of missing) {
    const day = Math.min(p.recurringAnchorDay || (toDate(p.date)?.getDate()) || 30, 31);
    const date = new Date(YEAR, MONTH0, day, 12, 0, 0);
    total += Number(p.amount) || 0;
    console.log(`  ${APPLY ? 'CREATE' : 'WOULD ADD'}: ${p.title} | ${p.amount} ${p.currency || 'ALL'} | ${p.category} | ${date.toISOString().slice(0, 10)}${p.memberId ? ' | member' : ''}`);
    if (APPLY) {
      await db.collection('expenses').add({
        title: p.title,
        description: p.description || null,
        amount: p.amount,
        currency: p.currency || 'ALL',
        category: p.category,
        teamId: p.teamId || null,
        businessId: p.businessId || null,
        projectId: p.projectId || null,
        departmentId: p.departmentId || null,
        memberId: p.memberId || null,
        isRecurring: false,
        autoGenerated: true,
        parentExpenseId: p.id,
        periodKey: PERIOD_KEY,
        status: p.status || 'Active',
        approvalStatus: 'Approved', // backfill of real committed costs → counts in P&L
        createdByUserId: p.createdByUserId || null,
        date: Timestamp.fromDate(date),
        backfill: 'july-2026',       // traceable / reversible tag
        createdAt: Timestamp.now(),
        updatedAt: Timestamp.now(),
      });
      created++;
    }
  }

  console.log('──────── Summary ────────');
  console.log(`Active monthly recurring series : ${parents.length}`);
  console.log(`Already had a July row (skipped): ${already}`);
  console.log(`${APPLY ? 'CREATED' : 'WOULD CREATE'} for July          : ${APPLY ? created : missing.length}`);
  console.log(`Total added to July (native)    : ${Math.round(total).toLocaleString()}`);
  if (!APPLY) console.log('\nRun again with --apply to write.');
}
main().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1); });

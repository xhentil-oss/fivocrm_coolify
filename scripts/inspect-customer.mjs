// Read-only: inspect a customer + their invoices and whether they'd reflect in profit.
// Usage: node scripts/inspect-customer.mjs "Gliozheni"
import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';

const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const needle = (process.argv[2] || 'Gliozheni').toLowerCase();
const d = (v) => (v?.toDate ? v.toDate().toISOString().slice(0, 10) : (v ? String(v).slice(0, 10) : '—'));

const [custSnap, invSnap, projSnap] = await Promise.all([
  db.collection('customers').get(),
  db.collection('invoices').get(),
  db.collection('projects').get(),
]);

const customers = custSnap.docs.filter(c => (c.data().name || '').toLowerCase().includes(needle));
if (!customers.length) { console.log(`No customer matching "${needle}"`); process.exit(0); }

const projById = new Map(projSnap.docs.map(p => [p.id, p.data()]));

for (const c of customers) {
  const cust = c.data();
  console.log(`\n=== Customer: ${cust.name}  (id=${c.id})  businessId=${cust.businessId || '—'} ===`);
  const invs = invSnap.docs.filter(i => i.data().customerId === c.id);
  console.log(`Invoices: ${invs.length}`);
  for (const iDoc of invs) {
    const i = iDoc.data();
    const proj = i.projectId ? projById.get(i.projectId) : null;
    console.log(`  • ${i.invoiceNumber || iDoc.id.slice(0,8)} | ${i.currency||'ALL'} total=${i.total ?? i.amount ?? 0} | status=${i.status} | invoiceDate=${d(i.invoiceDate)} paidAt=${d(i.paidAt)} | paidAmount=${i.paidAmount ?? 0}`);
    console.log(`      projectId=${i.projectId || '— (JO i lidhur me projekt)'}${proj ? ` → "${proj.name}" budget=${proj.budget ?? 0} dept=${proj.department||'—'}` : ''} | recurring=${!!i.isRecurring} autoGen=${!!i.autoGenerated} businessId=${i.businessId||'—'}`);
  }
}
process.exit(0);

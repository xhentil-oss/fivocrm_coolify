// Seritë periodike të shpenzimeve (paga, qira, abonime): pse (nuk) u krijua
// rreshti i një periudhe, dhe — me --apply — krijimi i rreshtave të munguar.
//
//   node scripts/audit-recurring-expenses.mjs                       → raport vetëm-lexim, periudha e kaluar
//   node scripts/audit-recurring-expenses.mjs --period=2026-09      → raport për atë periudhë
//   node scripts/audit-recurring-expenses.mjs --period=2026-09 --category=Salary
//   node scripts/audit-recurring-expenses.mjs --period=2026-09 --apply   → KRIJON rreshtat e munguar
//
// Pa --apply nuk shkruan asgjë. Me --apply krijon për çdo seri aktive, mujore,
// që nuk ka rresht për periudhën, një fëmijë me id-në e njëjtë që do shkruante
// cron-i (`rec_exp_<parentId>_<periudha>`, create() — kurrë dy herë), me të
// njëjtat fusha, dhe e çon pointer-in e serisë përpara vetëm nëse ka mbetur
// në/para asaj periudhe. Një muaj i mbyllur (`financeMonthCloses.locked`)
// refuzohet. Ky është "vendimi i pronarit" që motori lë qëllimisht jashtë
// cron-it (CLAUDE.md → Recurring EXPENSES: never backfill).

import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore, Timestamp } from 'firebase-admin/firestore';

const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const TZ = 'Europe/Tirane';
const arg = (name) => { const a = process.argv.find((x) => x.startsWith(`--${name}=`)); return a ? a.slice(name.length + 3) : null; };
const APPLY = process.argv.includes('--apply');
const CATEGORY = arg('category');
const NOW = new Date();
const p2 = (n) => String(n).padStart(2, '0');
function zoned(d) {
  const f = new Intl.DateTimeFormat('en-CA', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit' });
  const [y, m, day] = f.format(d).split('-').map(Number);
  return { year: y, month: m, day };
}
const monthKey = (d) => { const z = zoned(d); return `${z.year}-${p2(z.month)}`; };
const prevMonthKey = () => { const z = zoned(NOW); const m = z.month === 1 ? 12 : z.month - 1; const y = z.month === 1 ? z.year - 1 : z.year; return `${y}-${p2(m)}`; };
const PERIOD = arg('period') || prevMonthKey();
if (!/^\d{4}-\d{2}$/.test(PERIOD)) { console.error('--period duhet YYYY-MM'); process.exit(1); }
const [PY, PM] = PERIOD.split('-').map(Number);
const daysInMonth = (y, m) => new Date(Date.UTC(y, m, 0)).getUTCDate();
/** Mesditë Europe/Tirane e ditës së kërkuar (12:00 lokal = 10:00Z verë / 11:00Z dimër). */
function zonedNoon(y, m, day) {
  const guess = new Date(Date.UTC(y, m - 1, day, 12));
  const local = new Intl.DateTimeFormat('en-US', { timeZone: TZ, hour: 'numeric', hour12: false }).format(guess);
  const offsetH = Number(local) - 12;
  return new Date(guess.getTime() - offsetH * 3600_000);
}
const dt = (v) => (v?.toDate ? v.toDate() : (v ? new Date(v) : null));
const iso = (d) => (d && !isNaN(d.getTime()) ? d.toISOString().slice(0, 10) : '—');

console.log(`Periudha: ${PERIOD}   sot: ${monthKey(NOW)}   ${APPLY ? '*** APPLY: do të shkruajë ***' : '(vetëm lexim; shto --apply për të krijuar)'}\n`);

const parents = await db.collection('expenses').where('isRecurring', '==', true).get();
const bizSnap = await db.collection('businesses').get();
const bizName = new Map(bizSnap.docs.map((d) => [d.id, `${d.data().name || d.id} [${d.data().status || 'pa status'}]`]));
const closeCache = new Map();
async function monthLocked(bid) {
  const k = `${bid}_${PERIOD}`;
  if (!closeCache.has(k)) { const s = await db.collection('financeMonthCloses').doc(k).get(); closeCache.set(k, !!(s.exists && s.data().locked)); }
  return closeCache.get(k);
}

const summary = {};
const tally = (r) => { summary[r] = (summary[r] || 0) + 1; };
let created = 0;

for (const doc of parents.docs) {
  const e = doc.data();
  if (e.autoGenerated) continue;
  if (CATEGORY && e.category !== CATEGORY) continue;
  const freq = e.recurringFrequency || 'monthly';
  const ownDate = dt(e.date) || dt(e.createdAt);
  const nextDate = dt(e.nextRecurringDate);
  const anchor = Number(e.recurringAnchorDay) || (nextDate ? zoned(nextDate).day : (ownDate ? zoned(ownDate).day : 1));

  const children = await db.collection('expenses').where('parentExpenseId', '==', doc.id).get();
  const byPeriod = new Map();
  for (const c of children.docs) {
    const cd = c.data();
    const k = cd.periodKey || (dt(cd.date) ? monthKey(dt(cd.date)) : '?');
    byPeriod.set(k, [...(byPeriod.get(k) || []), c.id]);
  }
  const have = byPeriod.get(PERIOD) || [];

  let reason = null;
  if (freq !== 'monthly') reason = `frekuencë ${freq} (skripti trajton vetëm mujoret)`;
  else if (e.status && e.status !== 'Active') reason = 'inactive';
  else if (e.isRecurringPaused) reason = 'paused';
  else if (ownDate && monthKey(ownDate) === PERIOD) reason = 'vetë prindi është rreshti i këtij muaji';
  else if (ownDate && monthKey(ownDate) > PERIOD) reason = 'seria fillon pas kësaj periudhe';
  else if (dt(e.recurringEndDate) && monthKey(dt(e.recurringEndDate)) < PERIOD) reason = 'series-ended';
  else if (have.length) reason = `OK — ekziston (${have.join(', ')})`;
  else if (e.lastGeneratedPeriodKey === PERIOD) reason = 'lastGeneratedPeriodKey e pretendon, por nuk ka rresht (fshirë me dorë?)';
  else reason = 'MUNGON';

  const missing = reason === 'MUNGON';
  tally(missing ? 'MUNGON' : reason.startsWith('OK') ? 'OK' : reason);
  console.log(`· ${e.title}  ${e.amount} ${e.currency || 'ALL'}  [${e.category}]  ${bizName.get(e.businessId) || e.businessId}`);
  console.log(`  data e prindit: ${iso(ownDate)}  next: ${iso(nextDate)}  anchor: ${anchor}  lastKey: ${e.lastGeneratedPeriodKey ?? '—'}  paused: ${!!e.isRecurringPaused}  status: ${e.status ?? '—'}  skipped: ${e.recurringPeriodsSkipped ?? 0}`);
  console.log(`  fëmijë: ${[...byPeriod.keys()].sort().slice(-4).join(', ') || 'asnjë'}`);
  console.log(`  ⇒ ${PERIOD}: ${reason}`);

  if (!missing || !APPLY) continue;
  if (await monthLocked(e.businessId)) { console.log('  ✗ muaji është i mbyllur (financeMonthCloses.locked) — rihape në Financat para se ta krijosh'); tally('month-closed'); continue; }

  const day = Math.min(anchor, daysInMonth(PY, PM));
  const occurrence = zonedNoon(PY, PM, day);
  const childRef = db.collection('expenses').doc(`rec_exp_${doc.id}_${PERIOD}`);
  const child = {
    title: e.title, description: e.description || null, amount: e.amount, currency: e.currency || 'ALL', category: e.category,
    teamId: e.teamId || null, businessId: e.businessId || null, projectId: e.projectId || null, departmentId: e.departmentId || null,
    memberId: e.memberId || null, isRecurring: false, autoGenerated: true, parentExpenseId: doc.id, periodKey: PERIOD,
    status: e.status || 'Active',
    approvalStatus: e.approvalStatus === 'Rejected' ? 'Submitted' : (e.approvalStatus || 'Submitted'),
    approvedByUserId: e.approvalStatus === 'Approved' ? (e.approvedByUserId || null) : null,
    createdByUserId: e.createdByUserId || null,
    date: Timestamp.fromDate(occurrence), createdAt: Timestamp.now(), updatedAt: Timestamp.now(),
    backfilledBy: 'scripts/audit-recurring-expenses.mjs',
  };
  try { await childRef.create(child); } catch (err) {
    if (String(err?.code) === '6' || /ALREADY_EXISTS/i.test(String(err?.message))) { console.log('  = ekzistonte tashmë (id determinist)'); continue; }
    throw err;
  }
  // Pointer-i: vetëm nëse ka mbetur në/para kësaj periudhe (cron-i e ka çuar
  // ndoshta tashmë përpara si 'stale-period'; atë nuk e prekim).
  const patch = { updatedAt: Timestamp.now() };
  if (!nextDate || monthKey(nextDate) <= PERIOD) {
    const ny = PM === 12 ? PY + 1 : PY, nm = PM === 12 ? 1 : PM + 1;
    patch.nextRecurringDate = Timestamp.fromDate(zonedNoon(ny, nm, Math.min(anchor, daysInMonth(ny, nm))));
    patch.lastGeneratedPeriodKey = PERIOD;
    patch.recurringAnchorDay = anchor;
  }
  await doc.ref.update(patch);
  created++;
  console.log(`  ✓ u krijua ${childRef.id} me datë ${iso(occurrence)}`);
}

console.log('\nPërmbledhje:', summary, APPLY ? `— u krijuan ${created}` : '');
if (!APPLY && summary.MUNGON) console.log(`\nPër t'i krijuar: node scripts/audit-recurring-expenses.mjs --period=${PERIOD}${CATEGORY ? ` --category=${CATEGORY}` : ''} --apply`);

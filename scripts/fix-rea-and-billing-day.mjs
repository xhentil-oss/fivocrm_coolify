// One-off: (A) fix the REA double-billing, (B) set billingDayOfMonth=25 on all
// monthly recurring projects.  Dry-run by default; pass --apply to write.
//
//   node scripts/fix-rea-and-billing-day.mjs
//   node scripts/fix-rea-and-billing-day.mjs --apply

import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore, Timestamp } from 'firebase-admin/firestore';

const APPLY = process.argv.includes('--apply');
const BILLING_DAY = 25;
const REA_PROJECT_ID = 'uph5CcAs5FQmd67erQgM';
const REA_PARENT_INVOICE_ID = 'JWAvFcWbNoJY0IjfuE6l';       // FAT-006
const REA_DUP_JULY_NUMBER = 'REC-2026-07-24-JWAVFC';

const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const monthlyRecurring = (p) =>
  p.isRecurring === true && (p.recurringFrequency || 'monthly') === 'monthly'
  && !['Cancelled', 'Archived'].includes(p.status);

async function main() {
  console.log(`[fix] mode=${APPLY ? 'APPLY' : 'DRY-RUN'}`);
  const [projSnap, invSnap, custSnap] = await Promise.all([
    db.collection('projects').get(),
    db.collection('invoices').get(),
    db.collection('customers').get(),
  ]);
  const projects = projSnap.docs.map(d => ({ id: d.id, ref: d.ref, ...d.data() }));
  const invoices = invSnap.docs.map(d => ({ id: d.id, ref: d.ref, ...d.data() }));

  // ── A) REA ──
  console.log('\n=== A) REA (rearent.al - seo) ===');
  const rea = projects.find(p => p.id === REA_PROJECT_ID);
  const reaCust = custSnap.docs.find(c => (c.data().name || '').toLowerCase().includes('rea rental'));
  if (!rea) { console.log('  ⚠ projekti nuk u gjet'); }
  else {
    console.log(`  projekt: billingType ${rea.billingType} → monthly | billingDayOfMonth ${rea.billingDayOfMonth ?? '—'} → ${BILLING_DAY} | customerId ${rea.customerId ?? '—'} → ${reaCust ? reaCust.id + ' (' + reaCust.data().name + ')' : '⚠ klienti nuk u gjet'}`);
    if (APPLY) {
      const patch = { billingType: 'monthly', billingDayOfMonth: BILLING_DAY, updatedAt: Timestamp.now() };
      if (reaCust) patch.customerId = reaCust.id;
      await rea.ref.update(patch);
    }
  }
  const parent = invoices.find(i => i.id === REA_PARENT_INVOICE_ID);
  if (parent) {
    console.log(`  faturë-nënë ${parent.invoiceNumber}: isRecurring ${parent.isRecurring} → false (ndal bijat REC-*)`);
    if (APPLY) await parent.ref.update({ isRecurring: false, nextRecurringDate: null, recurringStoppedReason: 'duplicate-with-project-engine', updatedAt: Timestamp.now() });
  }
  const dup = invoices.find(i => i.invoiceNumber === REA_DUP_JULY_NUMBER);
  if (dup) {
    console.log(`  dublikata e Korrikut ${dup.invoiceNumber} (${dup.status}) → Cancelled`);
    if (APPLY) await dup.ref.update({ status: 'Cancelled', locallyCancelled: true, cancelReason: 'duplicate-double-engine-july-2026', updatedAt: Timestamp.now() });
  }

  // ── B) billingDayOfMonth = 25 on every monthly recurring project ──
  console.log(`\n=== B) billingDayOfMonth=${BILLING_DAY} për projektet mujore ===`);
  const monthly = projects.filter(monthlyRecurring);
  let set = 0, already = 0;
  for (const p of monthly) {
    if (p.billingDayOfMonth === BILLING_DAY) { already++; continue; }
    console.log(`  ${APPLY ? 'SET' : 'WOULD SET'}: "${p.name}" (${p.billingDayOfMonth ?? '—'} → ${BILLING_DAY}) | billingType=${p.billingType ?? '—'}`);
    if (APPLY) await p.ref.update({ billingDayOfMonth: BILLING_DAY, updatedAt: Timestamp.now() });
    set++;
  }
  console.log(`  Projekte mujore: ${monthly.length} | ${APPLY ? 'u vendos' : 'do vendoset'}: ${set} | tashmë 25: ${already}`);

  // ── C) Report other projects still running BOTH engines ──
  console.log('\n=== C) Projekte qe ende kane TE DY motoret (rrezik dyfishimi) ===');
  const others = [];
  for (const inv of invoices) {
    if (!inv.isRecurring || inv.autoGenerated || !inv.projectId) continue;
    if (inv.id === REA_PARENT_INVOICE_ID) continue; // handled above
    const p = projects.find(x => x.id === inv.projectId);
    if (p && monthlyRecurring(p)) others.push({ proj: p, inv });
  }
  if (!others.length) console.log('  (asnjë)');
  others.forEach(({ proj, inv }) => {
    console.log(`  ⚠ "${proj.name}" | billingType=${proj.billingType ?? '—'} | faturë-nënë ${inv.invoiceNumber || inv.id.slice(0, 6)} (${inv.total ?? inv.amount})`);
  });

  if (!APPLY) console.log('\nRun again with --apply to write.');
}
main().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1); });

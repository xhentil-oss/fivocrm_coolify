// Read-only: audit the expenses collection for (a) duplicates inside one month,
// (b) rows that can never appear in /app/expenses, (c) stalled recurring series.
// Usage: node scripts/inspect-expenses.mjs [businessIdFilter]
import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';

const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const only = process.argv[2] || null;
const toDate = (v) => {
  if (!v) return null;
  const d = v?.toDate ? v.toDate() : new Date(v);
  return d instanceof Date && !isNaN(d.getTime()) ? d : null;
};
// Mirrors src/lib/finance/financialAnalytics.ts → getExpenseDate
const expDate = (x) => toDate(x.date) || toDate(x.createdAt);
const ym = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
const iso = (d) => (d ? d.toISOString().slice(0, 10) : '—');

const [expSnap, bizSnap] = await Promise.all([
  db.collection('expenses').get(),
  db.collection('businesses').get(),
]);
const bizName = new Map(bizSnap.docs.map((b) => [b.id, b.data().name || b.id]));

let rows = expSnap.docs.map((d) => ({ id: d.id, ...d.data() }));
if (only) rows = rows.filter((r) => r.businessId === only);

console.log(`\n=== ${rows.length} shpenzime totale (${bizSnap.size} biznese) ===`);
const byBiz = new Map();
rows.forEach((r) => byBiz.set(r.businessId || '—', (byBiz.get(r.businessId || '—') || 0) + 1));
for (const [b, n] of [...byBiz].sort((a, b2) => b2[1] - a[1])) {
  console.log(`  ${String(n).padStart(4)}  ${b === '—' ? '(pa businessId)' : `${bizName.get(b) || '?'} [${b}]`}`);
}

// ── 1. Invisible rows ───────────────────────────────────────────────────────
const noBiz = rows.filter((r) => !r.businessId);
const noDate = rows.filter((r) => !expDate(r));
console.log(`\n=== A. Nuk shfaqen / probleme skopi ===`);
console.log(`Pa businessId (invisible në /app/expenses): ${noBiz.length}`);
noBiz.slice(0, 25).forEach((r) =>
  console.log(`   • ${r.title} | ${r.amount} ${r.currency || 'ALL'} | ${iso(expDate(r))} | auto=${!!r.autoGenerated} parent=${r.parentExpenseId || '—'} teamId=${r.teamId || '—'}`),
);
console.log(`Pa date & pa createdAt (mungojnë nga grafiku/filtrat e muajit): ${noDate.length}`);
noDate.slice(0, 15).forEach((r) => console.log(`   • ${r.title} | ${r.amount} ${r.currency || 'ALL'} | id=${r.id}`));
const noCreatedAt = rows.filter((r) => !toDate(r.createdAt));
console.log(`Pa createdAt (renditja default i çon në fund): ${noCreatedAt.length}`);

// ── 2. Duplicates inside one month ──────────────────────────────────────────
console.log(`\n=== B. Dublikatë brenda të njëjtit muaj ===`);
const groups = new Map();
for (const r of rows) {
  const d = expDate(r);
  if (!d) continue;
  const key = [r.businessId || '—', (r.title || '').trim().toLowerCase(), Number(r.amount) || 0, r.currency || 'ALL', ym(d)].join('|');
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(r);
}
const dups = [...groups.entries()].filter(([, v]) => v.length > 1);
let dupAmount = 0;
console.log(`Grupe me >1 rresht identik (titull+shumë+monedhë+muaj): ${dups.length}`);
for (const [key, list] of dups.sort((a, b) => b[1].length - a[1].length)) {
  const [bid, title, amount, cur, month] = key.split('|');
  dupAmount += (list.length - 1) * Number(amount);
  const kinds = list.map((r) => (r.autoGenerated ? 'auto' : r.isRecurring ? 'PRIND' : 'manual')).join(' + ');
  console.log(`\n  ✖ ${month} · "${title}" · ${amount} ${cur} · ×${list.length}  [${kinds}]  biz=${bizName.get(bid) || bid}`);
  list.forEach((r) =>
    console.log(`      - id=${r.id} date=${iso(expDate(r))} createdAt=${iso(toDate(r.createdAt))} auto=${!!r.autoGenerated} recurring=${!!r.isRecurring} parent=${r.parentExpenseId || '—'} approval=${r.approvalStatus || '—'}`),
  );
}
console.log(`\n  Mbi-numërim total nga dublikatat: ~${Math.round(dupAmount).toLocaleString()} (në monedhat përkatëse)`);

// ── 3. Parent vs child in the same month ────────────────────────────────────
console.log(`\n=== C. Prindi periodik + fëmija i gjeneruar në të njëjtin muaj ===`);
const childrenOf = new Map();
rows.forEach((r) => {
  if (!r.parentExpenseId) return;
  if (!childrenOf.has(r.parentExpenseId)) childrenOf.set(r.parentExpenseId, []);
  childrenOf.get(r.parentExpenseId).push(r);
});
let overlap = 0;
for (const p of rows.filter((r) => childrenOf.has(r.id))) {
  const pd = expDate(p);
  if (!pd) continue;
  const clash = (childrenOf.get(p.id) || []).filter((c) => {
    const cd = expDate(c);
    return cd && ym(cd) === ym(pd);
  });
  if (clash.length) {
    overlap++;
    console.log(`  ✖ "${p.title}" ${p.amount} ${p.currency || 'ALL'} · prindi ${iso(pd)} + ${clash.length} fëmijë në ${ym(pd)}`);
    clash.forEach((c) => console.log(`      - fëmijë id=${c.id} date=${iso(expDate(c))}`));
  }
}
console.log(`  Gjithsej seri me mbivendosje prind/fëmijë: ${overlap}`);

// ── 4. Recurring health ─────────────────────────────────────────────────────
console.log(`\n=== D. Shëndeti i serive periodike ===`);
const now = new Date();
const parents = rows.filter((r) => r.isRecurring && !r.autoGenerated);
console.log(`Prindër periodikë aktivë: ${parents.length}`);
const cycleDays = { weekly: 7, monthly: 31, yearly: 366 };
for (const p of parents) {
  const nrd = toDate(p.nextRecurringDate);
  const kids = childrenOf.get(p.id) || [];
  const lastKid = kids.map((k) => toDate(k.createdAt)).filter(Boolean).sort((a, b) => b - a)[0] || null;
  const flags = [];
  if (!nrd) flags.push('PA nextRecurringDate → nuk gjeneron KURRË');
  else {
    const lateDays = Math.floor((now - nrd) / 86400000);
    const cyc = cycleDays[p.recurringFrequency] || 31;
    if (lateDays > cyc) flags.push(`nextRecurringDate ${lateDays}d në të kaluarën (>${cyc}d = 1 cikël)`);
    // The cron's guard is `lastChildCreatedAt >= nextRecurringDate` → permanent stall.
    if (lastKid && nrd && lastKid >= nrd) flags.push('BLLOKUAR nga guard-i i cron-it (lastChild.createdAt >= nextRecurringDate)');
  }
  if (p.isRecurringPaused) flags.push('në pauzë');
  if (!p.recurringFrequency) flags.push('pa frekuencë');
  if (!p.businessId) flags.push('pa businessId');
  if (flags.length) {
    console.log(`  ⚠ "${p.title}" ${p.amount} ${p.currency || 'ALL'} freq=${p.recurringFrequency || '—'} next=${iso(nrd)} kids=${kids.length} lastKid=${iso(lastKid)}`);
    flags.forEach((f) => console.log(`      → ${f}`));
  }
}

// ── 5. Gaps in a generated series (setMonth overflow / missed months) ───────
console.log(`\n=== E. Muaj që mungojnë brenda një serie ===`);
for (const p of parents) {
  const kids = (childrenOf.get(p.id) || []).map((k) => expDate(k)).filter(Boolean).sort((a, b) => a - b);
  if (kids.length < 2 || p.recurringFrequency !== 'monthly') continue;
  const months = new Set(kids.map(ym));
  const cur = new Date(kids[0].getFullYear(), kids[0].getMonth(), 1);
  const end = kids[kids.length - 1];
  const missing = [];
  while (cur <= end) {
    if (!months.has(ym(cur))) missing.push(ym(cur));
    cur.setMonth(cur.getMonth() + 1);
  }
  if (missing.length) console.log(`  ⚠ "${p.title}" mungojnë: ${missing.join(', ')}  (fëmijë: ${kids.length})`);
}

process.exit(0);

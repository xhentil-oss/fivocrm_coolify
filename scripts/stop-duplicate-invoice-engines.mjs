// Stop the INVOICE recurrence on projects whose PROJECT engine already bills them
// (two engines must not overlap). Also reports any same-month duplicates.
//   node scripts/stop-duplicate-invoice-engines.mjs           (dry-run)
//   node scripts/stop-duplicate-invoice-engines.mjs --apply

import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore, Timestamp } from 'firebase-admin/firestore';

const APPLY = process.argv.includes('--apply');
const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const db = getFirestore();

const dt = (v) => (v?.toDate ? v.toDate() : (v ? new Date(v) : null));
const monthKey = (d) => (d ? `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}` : '?');
const monthlyRecurring = (p) =>
  p.isRecurring === true && (p.recurringFrequency || 'monthly') === 'monthly'
  && !['Cancelled', 'Archived'].includes(p.status);

async function main() {
  console.log(`[stop-engines] mode=${APPLY ? 'APPLY' : 'DRY-RUN'}`);
  const [projSnap, invSnap] = await Promise.all([
    db.collection('projects').get(), db.collection('invoices').get(),
  ]);
  const projects = new Map(projSnap.docs.map(d => [d.id, { id: d.id, ...d.data() }]));
  const invoices = invSnap.docs.map(d => ({ id: d.id, ref: d.ref, ...d.data() }));

  // Parent recurring invoices attached to a project the PROJECT engine also bills.
  const targets = invoices.filter(i => {
    if (!i.isRecurring || i.autoGenerated || !i.projectId) return false;
    const p = projects.get(i.projectId);
    return !!p && monthlyRecurring(p);
  });

  if (!targets.length) { console.log('  Asnjë projekt me të dy motorët. ✓'); return; }

  for (const inv of targets) {
    const p = projects.get(inv.projectId);
    console.log(`\n• "${p.name}" — faturë-nënë ${inv.invoiceNumber || inv.id.slice(0, 8)} (${inv.total ?? inv.amount} ${inv.currency || 'ALL'})`);
    console.log(`    isRecurring ${inv.isRecurring} → false | next ${dt(inv.nextRecurringDate)?.toISOString().slice(0, 10) || '—'} → null`);

    // Same-month duplicates for this project (project-engine vs invoice-engine)
    const mine = invoices.filter(x => x.projectId === inv.projectId && x.status !== 'Cancelled');
    const byMonth = new Map();
    mine.forEach(x => {
      const k = monthKey(dt(x.invoiceDate) || dt(x.createdAt));
      if (!byMonth.has(k)) byMonth.set(k, []);
      byMonth.get(k).push(x);
    });
    [...byMonth.entries()].filter(([, a]) => a.length > 1).forEach(([k, a]) => {
      console.log(`    ⚠ ${k}: ${a.length} fatura → ${a.map(x => `${x.invoiceNumber || x.id.slice(0, 6)}(${x.status})`).join(', ')}`);
    });

    if (APPLY) {
      await inv.ref.update({
        isRecurring: false,
        nextRecurringDate: null,
        recurringStoppedReason: 'duplicate-with-project-engine',
        updatedAt: Timestamp.now(),
      });
      console.log('    ✓ ndalur');
    }
  }
  if (!APPLY) console.log('\nRun again with --apply to write.');
}
main().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1); });

// One-time backfill: copy products from recurring PARENT invoices onto their
// already-generated CHILD invoices that were created empty (before the cron fix).
// Safe & idempotent: only touches children with NO products; never edits amounts.
//
// Run:  node scripts/backfill-recurring-products.mjs           (dry-run, count only)
//       node scripts/backfill-recurring-products.mjs --apply   (write)

import { readFileSync } from 'node:fs';
import { initializeApp, getApps, cert } from 'firebase-admin/app';
import { getFirestore, Timestamp } from 'firebase-admin/firestore';

// Dry-run by default like every other maintenance script; `--apply` writes.
const DRY = !process.argv.includes('--apply');

// ── Credentials from the service-account key (scripts/sa.json) ──
const sa = JSON.parse(readFileSync('scripts/sa.json', 'utf8'));
if (!getApps().length) initializeApp({ credential: cert(sa) });
const projectId = sa.project_id;
const db = getFirestore();

const hasArr = (v) => Array.isArray(v) && v.length > 0;

async function main() {
  console.log(`[backfill] project=${projectId} mode=${DRY ? 'DRY-RUN' : 'APPLY'}`);

  const [invSnap, itemsSnap] = await Promise.all([
    db.collection('invoices').get(),
    db.collection('invoiceItems').get(),
  ]);

  // invoiceId -> its invoiceItems docs
  const itemsByInvoice = new Map();
  for (const d of itemsSnap.docs) {
    const it = d.data();
    if (!it.invoiceId) continue;
    if (!itemsByInvoice.has(it.invoiceId)) itemsByInvoice.set(it.invoiceId, []);
    itemsByInvoice.get(it.invoiceId).push(it);
  }
  const invById = new Map(invSnap.docs.map(d => [d.id, { id: d.id, ...d.data() }]));

  const children = invSnap.docs
    .map(d => ({ id: d.id, ...d.data() }))
    .filter(i => i.autoGenerated === true);

  let alreadyHad = 0, noParent = 0, parentEmpty = 0, fixed = 0, itemsCreated = 0;
  const batchWrites = [];

  for (const child of children) {
    const childHasProducts =
      (itemsByInvoice.get(child.id)?.length > 0) || hasArr(child.lineItems) || !!child.productSummary;
    if (childHasProducts) { alreadyHad++; continue; }

    const parent = child.parentInvoiceId ? invById.get(child.parentInvoiceId) : null;
    if (!parent) { noParent++; continue; }

    const parentItems = itemsByInvoice.get(parent.id) || [];
    const parentLineItems = hasArr(parent.lineItems) ? parent.lineItems : null;
    const parentSummary = parent.productSummary || null;

    if (parentItems.length === 0 && !parentLineItems && !parentSummary) { parentEmpty++; continue; }

    if (!DRY) {
      // Copy invoiceItems collection docs
      for (const it of parentItems) {
        const ref = db.collection('invoiceItems').doc();
        batchWrites.push(ref.set({
          invoiceId: child.id,
          serviceId: it.serviceId || null,
          description: it.description || '',
          quantity: it.quantity || 1,
          unitPrice: it.unitPrice || 0,
          totalPrice: it.totalPrice || 0,
          teamId: it.teamId || child.teamId || null,
          createdAt: Timestamp.now(),
          updatedAt: Timestamp.now(),
        }));
        itemsCreated++;
      }
      // Copy inline products (WHMCS/shop origin)
      const patch = { updatedAt: Timestamp.now() };
      if (parentLineItems) patch.lineItems = parentLineItems;
      if (parentSummary) patch.productSummary = parentSummary;
      if (parentLineItems || parentSummary) {
        batchWrites.push(db.collection('invoices').doc(child.id).update(patch));
      }
    }
    fixed++;
  }

  if (!DRY && batchWrites.length) {
    // settle in chunks to stay well under any limits
    const CHUNK = 200;
    for (let i = 0; i < batchWrites.length; i += CHUNK) {
      await Promise.all(batchWrites.slice(i, i + CHUNK));
    }
  }

  console.log('──────── Backfill summary ────────');
  console.log(`Auto-generated (child) invoices scanned : ${children.length}`);
  console.log(`Already had products (skipped)          : ${alreadyHad}`);
  console.log(`Missing parent link (skipped)           : ${noParent}`);
  console.log(`Parent itself had no products (skipped) : ${parentEmpty}`);
  console.log(`${DRY ? 'WOULD FIX' : 'FIXED'} children                       : ${fixed}`);
  if (!DRY) console.log(`invoiceItems rows created               : ${itemsCreated}`);
  console.log('──────────────────────────────────');
}

main().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1); });

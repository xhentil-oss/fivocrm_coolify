import { describe, expect, it } from 'vitest';
import type { Invoice, Expense, TeamMember } from '../../types';
import { computeCashflowHealth } from './cashflowAlarms';

const NOW = new Date('2026-07-15T12:00:00');

function mkInvoice(p: Partial<Invoice>): Invoice {
  return {
    id: p.id || 'i1', amount: p.amount ?? 0, status: p.status ?? 'Pending',
    createdAt: p.createdAt ?? new Date('2026-07-01'), ...p,
  } as Invoice;
}
function mkExpense(p: Partial<Expense>): Expense {
  return {
    id: p.id || 'e1', title: 'x', amount: p.amount ?? 0, category: p.category || 'Other',
    currency: p.currency || 'ALL', date: p.date ?? new Date('2026-07-01'), ...p,
  } as Expense;
}
function mkMember(p: Partial<TeamMember>): TeamMember {
  return { id: p.id || 'm1', teamId: 't1', userId: p.userId || 'u1', role: 'Member',
    status: p.status || 'Active', monthlySalary: p.monthlySalary, ...p } as TeamMember;
}

describe('computeCashflowHealth', () => {
  it('normalises recurring inflow and fixed outflow to per-month', () => {
    const invoices = [
      mkInvoice({ id: 'r', total: 50_000, status: 'Pending', isRecurring: true, recurringFrequency: 'monthly' }),
      mkInvoice({ id: 'y', total: 120_000, status: 'Pending', isRecurring: true, recurringFrequency: 'yearly' }), // → 10k/mo
    ];
    const members = [mkMember({ monthlySalary: 40_000 })];
    const res = computeCashflowHealth(invoices, [], members, [], NOW);
    expect(res.monthlyInflow).toBe(60_000); // 50k + 10k
    expect(res.monthlyOutflow).toBe(40_000);
    expect(res.gap).toBe(20_000);
    expect(res.alarms.find(a => a.id === 'cashflow-gap')).toBeUndefined();
  });

  it('counts monthly-billing projects as recurring inflow (no false gap alarm)', () => {
    // Retainer modelled as a monthly PROJECT (no recurring invoice). `isRecurring`
    // is what makes it a series — the inflow asks the billing engine.
    const projects = [
      { id: 'p1', name: 'Retainer', status: 'Active', budget: 120_000, billingType: 'monthly', isRecurring: true } as any,
    ];
    const members = [mkMember({ monthlySalary: 80_000 })];
    const res = computeCashflowHealth([], [], members, projects, NOW);
    expect(res.monthlyInflow).toBe(120_000);
    expect(res.gap).toBe(40_000);
    expect(res.alarms.find(a => a.id === 'cashflow-gap')).toBeUndefined();
  });

  it('stops counting a retainer whose billing series was switched off', () => {
    // The gap alarm is the one number meant to warn BEFORE the money runs out.
    // With `isRecurring` never checked, a stopped 120k retainer kept covering
    // the payroll on paper and the red alarm never fired.
    const projects = [
      { id: 'p1', name: 'Retainer', status: 'Active', budget: 120_000,
        billingType: 'monthly', isRecurring: false } as any,
    ];
    const members = [mkMember({ monthlySalary: 80_000 })];
    const res = computeCashflowHealth([], [], members, projects, NOW);
    expect(res.monthlyInflow).toBe(0);
    expect(res.gap).toBe(-80_000);
    expect(res.alarms.find(a => a.id === 'cashflow-gap')?.severity).toBe('red');
  });

  it('drops a recurring expense series that is past its end date', () => {
    const expenses = [
      mkExpense({ id: 'ended', amount: 60_000, category: 'Software', isRecurring: true,
        recurringFrequency: 'monthly', nextRecurringDate: new Date('2026-08-01'),
        recurringEndDate: new Date('2026-06-30') } as any),
      mkExpense({ id: 'live', amount: 20_000, category: 'Rent', isRecurring: true,
        recurringFrequency: 'monthly' } as any),
    ];
    const res = computeCashflowHealth([], expenses, [], [], NOW);
    expect(res.recurringExpenses).toBe(20_000);
  });

  it('raises a red alarm when fixed costs exceed recurring income', () => {
    const invoices = [mkInvoice({ id: 'r', total: 30_000, status: 'Pending', isRecurring: true, recurringFrequency: 'monthly' })];
    const members = [mkMember({ monthlySalary: 100_000 })];
    const res = computeCashflowHealth(invoices, [], members, [], NOW);
    expect(res.gap).toBe(-70_000);
    const alarm = res.alarms.find(a => a.id === 'cashflow-gap');
    expect(alarm?.severity).toBe('red');
    expect(alarm?.amount).toBe(-70_000);
  });

  it('excludes paused/auto-generated recurring docs and Salary expenses', () => {
    const invoices = [
      mkInvoice({ id: 'p', total: 50_000, isRecurring: true, isRecurringPaused: true, recurringFrequency: 'monthly' }),
      mkInvoice({ id: 'c', total: 50_000, isRecurring: true, autoGenerated: true, recurringFrequency: 'monthly' }),
    ];
    const expenses = [
      mkExpense({ id: 's', amount: 99_000, category: 'Salary', isRecurring: true, recurringFrequency: 'monthly' }),
    ];
    const res = computeCashflowHealth(invoices, expenses, [], [], NOW);
    expect(res.monthlyInflow).toBe(0);
    expect(res.recurringExpenses).toBe(0);
  });

  it('flags receivables aged over 60 days', () => {
    const invoices = [
      mkInvoice({ id: 'old', total: 80_000, status: 'Pending', dueDate: new Date('2026-04-01') }), // ~105d overdue
    ];
    const res = computeCashflowHealth(invoices, [], [], [], NOW);
    expect(res.overdue60Plus).toBe(80_000);
    expect(res.alarms.find(a => a.id === 'overdue-60')?.severity).toBe('red');
  });

  it('detects single-client concentration over 40%', () => {
    const invoices = [
      mkInvoice({ id: 'a', total: 90_000, status: 'Paid', customerId: 'big', paidAt: new Date('2026-06-01') }),
      mkInvoice({ id: 'b', total: 10_000, status: 'Paid', customerId: 'small', paidAt: new Date('2026-06-01') }),
    ];
    const res = computeCashflowHealth(invoices, [], [], [], NOW);
    const c = res.alarms.find(a => a.id === 'concentration');
    expect(c?.customerId).toBe('big');
  });

  it('measures concentration over the THREE months its copy promises', () => {
    // NOW = 15 Jul 2026 → the window opens 1 May (May, Jun, Jul). Cash banked in
    // April is a FOURTH month: with the old `monthStart(now, -3)` window the
    // 90 000 below made 'big' the concentration risk, contradicting the copy.
    const invoices = [
      mkInvoice({ id: 'apr', total: 90_000, status: 'Paid', customerId: 'big', paidAt: new Date('2026-04-10') }),
      mkInvoice({ id: 'jun1', total: 10_000, status: 'Paid', customerId: 'big', paidAt: new Date('2026-06-10') }),
      mkInvoice({ id: 'jun2', total: 40_000, status: 'Paid', customerId: 'small', paidAt: new Date('2026-06-12') }),
    ];
    const res = computeCashflowHealth(invoices, [], [], [], NOW);
    const c = res.alarms.find(a => a.id === 'concentration');
    expect(c?.customerId).toBe('small');   // 40k of the 50k collected in May–Jul
    expect(c?.amount).toBe(40_000);
  });
});

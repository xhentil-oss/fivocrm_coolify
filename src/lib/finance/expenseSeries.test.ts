import { describe, it, expect } from 'vitest';
import type { Expense } from '../../types';
import {
  buildExpenseSeriesLedger,
  expenseSeriesHealth,
  periodLabel,
  periodShortLabel,
  findUnlinkedSiblings,
  linkSiblingPatch,
  backfillBlockReason,
  backfillOccurrenceDraft,
  backfillParentPatch,
  recurringExpenseOccurrenceId,
} from './expenseSeries';

const d = (s: string) => new Date(s + 'T10:00:00');

function exp(over: Partial<Expense> & { id: string }): Expense {
  return {
    title: 'Qira Zyre',
    amount: 50000,
    currency: 'ALL',
    category: 'Rent',
    createdAt: d('2026-03-05'),
    updatedAt: d('2026-03-05'),
    createdByUserId: 'u1',
    status: 'Active',
    approvalStatus: 'Approved',
    businessId: 'biz',
    ...over,
  } as Expense;
}

const parent = exp({
  id: 'p1',
  date: d('2026-03-05'),
  isRecurring: true,
  recurringFrequency: 'monthly',
  recurringAnchorDay: 5,
  nextRecurringDate: d('2026-10-05'),
  lastGeneratedPeriodKey: '2026-09',
});

const child = (key: string, over: Partial<Expense> = {}) => exp({
  id: `rec_exp_p1_${key}`,
  parentExpenseId: 'p1',
  autoGenerated: true,
  periodKey: key,
  date: d(`${key}-05`),
  ...over,
});

describe('periodLabel', () => {
  it('names each cadence in Albanian', () => {
    expect(periodLabel('2026-09')).toBe('Shtator 2026');
    expect(periodLabel('W2026-08-03')).toBe('Java e 3 Gus 2026');
    expect(periodLabel('Q2026-3')).toBe('T3 2026');
    expect(periodLabel('Y2026')).toBe('2026');
    expect(periodShortLabel('2026-09')).toBe('Sht 26');
  });
});

describe('buildExpenseSeriesLedger', () => {
  const now = d('2026-10-01');

  it('lists every period from the parent to today, marking gaps and the pending current one', () => {
    const kids = [child('2026-04'), child('2026-05'), child('2026-07'), child('2026-08'), child('2026-09')];
    const ledger = buildExpenseSeriesLedger(parent, kids, now);
    const states = Object.fromEntries(ledger.periods.map(p => [p.key, p.state]));
    expect(states).toEqual({
      '2026-03': 'booked',   // the parent row IS March
      '2026-04': 'booked',
      '2026-05': 'booked',
      '2026-06': 'missing',  // never generated
      '2026-07': 'booked',
      '2026-08': 'booked',
      '2026-09': 'booked',
      '2026-10': 'pending',  // due on the 5th, today is the 1st
      '2026-11': 'upcoming',
      '2026-12': 'upcoming',
    });
    expect(ledger.bookedCount).toBe(6);
    expect(ledger.missingCount).toBe(1);
    expect(ledger.totalNative).toBe(300000);
    expect(ledger.totalAll).toBe(300000);
    expect(ledger.averageAll).toBe(50000);
    expect(ledger.firstBookedAt).toEqual(d('2026-03-05'));
    expect(ledger.lastBookedAt).toEqual(d('2026-09-05'));
  });

  it('the current period is MISSING once its day has passed with no row', () => {
    const ledger = buildExpenseSeriesLedger(parent, [child('2026-04')], d('2026-10-20'));
    expect(ledger.periods.find(p => p.key === '2026-10')?.state).toBe('missing');
  });

  it('records amount changes between consecutive booked periods, with deltas', () => {
    const kids = [child('2026-04'), child('2026-05', { amount: 55000 }), child('2026-06', { amount: 55000 })];
    const ledger = buildExpenseSeriesLedger(parent, kids, d('2026-06-20'));
    expect(ledger.amountChanges).toEqual([
      { periodKey: '2026-05', label: 'Maj 2026', from: 50000, to: 55000, pct: 10 },
    ]);
    expect(ledger.periods.find(p => p.key === '2026-05')?.delta).toBe(5000);
    expect(ledger.periods.find(p => p.key === '2026-06')?.delta).toBe(0);
    expect(ledger.periods.find(p => p.key === '2026-03')?.delta).toBeNull();
  });

  it('flags two countable rows in one period as a duplicate and counts both in the total', () => {
    const kids = [child('2026-04'), exp({ id: 'manual', parentExpenseId: 'p1', date: d('2026-04-28') })];
    const ledger = buildExpenseSeriesLedger(parent, kids, d('2026-04-30'));
    const apr = ledger.periods.find(p => p.key === '2026-04')!;
    expect(apr.duplicate).toBe(true);
    expect(apr.amount).toBe(100000);
    expect(apr.origin).toBe('mixed');
    expect(ledger.duplicateCount).toBe(1);
  });

  it('a Rejected row keeps the period booked but counts nothing', () => {
    const kids = [child('2026-04', { approvalStatus: 'Rejected' })];
    const ledger = buildExpenseSeriesLedger(parent, kids, d('2026-04-30'));
    const apr = ledger.periods.find(p => p.key === '2026-04')!;
    expect(apr.state).toBe('booked');
    expect(apr.amount).toBe(0);
    expect(apr.approval).toBe('Rejected');
    expect(ledger.totalNative).toBe(50000); // the parent only
  });

  it('paid state needs every countable row paid', () => {
    const kids = [child('2026-04', { paidDate: d('2026-04-06') })];
    const ledger = buildExpenseSeriesLedger({ ...parent, paidDate: undefined }, kids, d('2026-04-30'));
    expect(ledger.periods.find(p => p.key === '2026-04')?.paid).toBe(true);
    expect(ledger.periods.find(p => p.key === '2026-03')?.paid).toBe(false);
    expect(ledger.paidCount).toBe(1);
    expect(ledger.unpaidCount).toBe(1);
  });

  it('a paused or stopped series ends at its last booked period — no missing, no upcoming', () => {
    const kids = [child('2026-04'), child('2026-05')];
    for (const over of [{ isRecurringPaused: true }, { isRecurring: false }, { status: 'Inactive' }]) {
      const ledger = buildExpenseSeriesLedger({ ...parent, ...over } as Expense, kids, now);
      expect(ledger.periods.map(p => p.key)).toEqual(['2026-03', '2026-04', '2026-05']);
      expect(ledger.missingCount).toBe(0);
    }
  });

  it('stops at the end date and lists no upcoming periods past it', () => {
    const ended = { ...parent, recurringEndDate: d('2026-06-30') };
    const ledger = buildExpenseSeriesLedger(ended, [child('2026-04')], d('2026-05-01'));
    expect(ledger.periods.map(p => p.key)).toEqual(['2026-03', '2026-04', '2026-05', '2026-06']);
    expect(ledger.periods.find(p => p.key === '2026-05')?.state).toBe('pending');
  });

  it('keeps the anchor day: a 31st series schedules Feb on the 28th and Mar on the 31st', () => {
    const p31 = exp({
      id: 'p31', date: d('2026-01-31'), isRecurring: true, recurringFrequency: 'monthly', recurringAnchorDay: 31,
      nextRecurringDate: d('2026-04-30'),
    });
    const ledger = buildExpenseSeriesLedger(p31, [], d('2026-03-15'));
    const days = ledger.periods.map(p => [p.key, p.scheduledAt.getDate()]);
    expect(days).toEqual([['2026-01', 31], ['2026-02', 28], ['2026-03', 31], ['2026-04', 30], ['2026-05', 31]]);
  });

  it('mixed currencies are flagged and still totalled in ALL', () => {
    const kids = [child('2026-04', { currency: 'EUR', amount: 500 })];
    const ledger = buildExpenseSeriesLedger(parent, kids, d('2026-04-30'));
    expect(ledger.mixedCurrency).toBe(true);
    expect(ledger.totalAll).toBeGreaterThan(50000);
    expect(ledger.periods.find(p => p.key === '2026-04')?.delta).toBeNull();
  });

  it('a weekly series walks by weeks', () => {
    const weekly = exp({
      id: 'w', date: d('2026-09-07'), isRecurring: true, recurringFrequency: 'weekly',
      nextRecurringDate: d('2026-09-28'), lastGeneratedPeriodKey: 'W2026-09-21',
    });
    const ledger = buildExpenseSeriesLedger(weekly, [], d('2026-09-23'));
    expect(ledger.periods.map(p => p.key)).toEqual(['W2026-09-07', 'W2026-09-14', 'W2026-09-21', 'W2026-09-28', 'W2026-10-05']);
    expect(ledger.periods.map(p => p.state)).toEqual(['booked', 'missing', 'missing', 'upcoming', 'upcoming']);
  });
});

describe('expenseSeriesHealth', () => {
  it('a running series commits its monthly rate and names the next due date', () => {
    const h = expenseSeriesHealth(parent, d('2026-10-01'));
    expect(h.block).toBe('not-due');
    expect(h.running).toBe(true);
    expect(h.isProblem).toBe(false);
    expect(h.monthlyAll).toBe(50000);
    expect(h.yearlyAll).toBe(600000);
    expect(h.nextDueAt).toEqual(d('2026-10-05'));
  });

  it('a series with no next date is a PROBLEM and commits nothing', () => {
    const h = expenseSeriesHealth({ ...parent, nextRecurringDate: undefined }, d('2026-10-01'));
    expect(h.block).toBe('no-next-date');
    expect(h.isProblem).toBe(true);
    expect(h.running).toBe(false);
    expect(h.monthlyAll).toBe(0);
  });

  it('a quarterly series commits a third per month', () => {
    const h = expenseSeriesHealth({ ...parent, recurringFrequency: 'quarterly' }, d('2026-10-01'));
    expect(h.monthlyAll).toBeCloseTo(50000 / 3);
  });
});

describe('unlinked siblings', () => {
  it('offers same-title rows outside the series, never another parent or an owned child', () => {
    const all = [
      parent,
      child('2026-04'),
      exp({ id: 'hand', title: ' qira  zyre ', date: d('2026-06-05') }),
      exp({ id: 'otherSeries', isRecurring: true }),
      exp({ id: 'owned', parentExpenseId: 'other' }),
      exp({ id: 'eur', currency: 'EUR' }),
      exp({ id: 'cat', category: 'Office' }),
    ];
    expect(findUnlinkedSiblings(parent, all).map(e => e.id)).toEqual(['hand']);
    expect(linkSiblingPatch(parent, all[2])).toEqual({ parentExpenseId: 'p1', periodKey: '2026-06' });
  });
});

describe('manual backfill', () => {
  const now = d('2026-10-01');
  const ledger = buildExpenseSeriesLedger(parent, [child('2026-04')], now);
  const june = ledger.periods.find(p => p.key === '2026-06')!;

  it('is allowed for a past missing period and refused for a closed month or a future one', () => {
    expect(backfillBlockReason(june, parent, [], now)).toBeNull();
    expect(backfillBlockReason(june, parent, [{ businessId: 'biz', periodKey: '2026-06', locked: true }], now)).toBe('month-closed');
    expect(backfillBlockReason(june, parent, [{ businessId: 'other', periodKey: '2026-06', locked: true }], now)).toBeNull();
    expect(backfillBlockReason(ledger.periods.find(p => p.key === '2026-04')!, parent, [], now)).toBe('not-missing');
    expect(backfillBlockReason(ledger.periods.find(p => p.key === '2026-11')!, parent, [], now)).toBe('future');
    expect(backfillBlockReason(june, { ...parent, category: 'Salary' }, [], now, false)).toBe('approver-only');
    expect(backfillBlockReason(june, { ...parent, category: 'Salary' }, [], now, true)).toBeNull();
  });

  it('a non-approver only ever SUBMITS the backfilled row', () => {
    const draft = backfillOccurrenceDraft(parent, june, 'me', false);
    expect(draft.data.approvalStatus).toBe('Submitted');
    expect(draft.data.approvedByUserId).toBeNull();
    expect(draft.data.teamId).toBeUndefined(); // stamped by the mutation hook, never null
  });

  it('writes the exact document the cron would have, under the cron id', () => {
    const draft = backfillOccurrenceDraft(parent, june, 'me');
    expect(draft.id).toBe(recurringExpenseOccurrenceId('p1', '2026-06'));
    expect(draft.data).toMatchObject({
      title: 'Qira Zyre', amount: 50000, currency: 'ALL', category: 'Rent',
      autoGenerated: true, isRecurring: false, parentExpenseId: 'p1', periodKey: '2026-06',
      approvalStatus: 'Approved', approvedByUserId: 'me', createdByUserId: 'me', businessId: 'biz',
    });
    expect(draft.data.date).toEqual(june.scheduledAt);
  });

  it('an OLD period never moves the claim or the pointer; a newer one does', () => {
    expect(backfillParentPatch(parent, june)).toBeNull();
    const stale = { ...parent, lastGeneratedPeriodKey: '2026-05', nextRecurringDate: d('2026-06-05') };
    const patch = backfillParentPatch(stale, june)!;
    expect(patch.lastGeneratedPeriodKey).toBe('2026-06');
    expect(patch.nextRecurringDate).toEqual(d('2026-07-05'));
  });
});

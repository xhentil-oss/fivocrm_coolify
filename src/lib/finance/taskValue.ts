import { addDoc, collection, doc, increment, updateDoc } from 'firebase/firestore';
import { db, getNextInvoiceNumber } from '../firebase';
import { getGlobalBusinessId } from '../../hooks/useFirestore';
import type { Project } from '../../types';

// ── Valued tasks (task.value) — one financial meaning everywhere ─────────────
//
// A task created with a monetary `value` produces TWO artefacts today:
//   1. its own DRAFT invoice (never revenue until reviewed & sent), and
//   2. a `budget: increment(value)` on the parent project.
//
// (2) is only correct for ONE-TIME projects, where `budget` means "total
// contract value" and extra scope legitimately grows it. On a RECURRING
// project, `budget` is the per-period retainer fee: incrementing it turns a
// one-off €200 task into +€200 on EVERY future auto-invoice — and the client
// already got the €200 draft invoice, so the same work double-bills, forever.
//
// This module is the single place that decision lives. It is used by
// ProjectDetailView (task create), the TasksView create path, and mirrored by
// scripts/backfill-task-value-into-budget.mjs — keep them in agreement.

export interface TaskValueDecision {
  /** The draft invoice is always right for a priced task — a draft can never
   *  collide with the project's own billing. */
  createDraftInvoice: boolean;
  /** Grow project.budget by the value — one-time projects only. */
  applyToBudget: boolean;
  /** Why applyToBudget is false, for the toast. */
  budgetBlockReason?: 'recurring-project' | 'no-project';
}

export function projectBillsRecurring(
  project?: Pick<Project, 'billingType' | 'isRecurring'> | null,
): boolean {
  if (!project) return false;
  // billingType wins when set; otherwise inferred from isRecurring — the same
  // inference the billing engine uses (see src/lib/finance/recurringBilling.ts).
  if (project.billingType === 'monthly') return true;
  if (project.billingType === 'one-time') return false;
  return !!project.isRecurring;
}

export function taskValueDecision(
  value: number,
  project?: Pick<Project, 'billingType' | 'isRecurring'> | null,
): TaskValueDecision {
  if (!value || value <= 0 || Number.isNaN(value)) {
    return { createDraftInvoice: false, applyToBudget: false };
  }
  if (!project) {
    return { createDraftInvoice: true, applyToBudget: false, budgetBlockReason: 'no-project' };
  }
  if (projectBillsRecurring(project)) {
    return { createDraftInvoice: true, applyToBudget: false, budgetBlockReason: 'recurring-project' };
  }
  return { createDraftInvoice: true, applyToBudget: true };
}

const stripUndefined = <T extends Record<string, unknown>>(obj: T): T => {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(obj)) if (v !== undefined) out[k] = v;
  return out as T;
};

export interface ValuedTaskResult {
  invoiceNumber?: string;
  appliedToBudget: boolean;
  skipped: boolean;
}

/**
 * The side-effects of a priced task, in one place: draft invoice + line item,
 * conditional budget increment, and the `valueAppliedToBudget` idempotency flag.
 * Used by ProjectDetailView AND TasksView, so a valued task means the same thing
 * no matter which surface created it (it used to mean three different things).
 */
export async function applyValuedTaskSideEffects(opts: {
  taskId: string;
  taskTitle: string;
  value: number;
  project?: (Pick<Project, 'billingType' | 'isRecurring' | 'customerId' | 'teamId' | 'name'> & { id: string; businessId?: string; currency?: string }) | null;
}): Promise<ValuedTaskResult> {
  const decision = taskValueDecision(opts.value, opts.project);
  if (!decision.createDraftInvoice) return { appliedToBudget: false, skipped: true };

  const businessId = opts.project?.businessId || getGlobalBusinessId() || undefined;
  const teamId = opts.project?.teamId;
  const scopeId = businessId || teamId;
  // No fallbackMax: the per-business counter is already seeded, so this avoids
  // reading every invoice just to allocate one number.
  const invoiceNumber = scopeId
    ? await getNextInvoiceNumber(scopeId)
    : `TASK-${Date.now().toString(36).toUpperCase()}`;
  const issuedAt = new Date();
  const due = new Date(issuedAt.getFullYear(), issuedAt.getMonth() + 1, 0, 23, 59, 59, 999);

  const invoiceRef = await addDoc(collection(db, 'invoices'), stripUndefined({
    invoiceNumber,
    projectId: opts.project?.id,
    customerId: opts.project?.customerId,
    teamId,
    businessId,
    amount: opts.value,
    subtotal: opts.value,
    total: opts.value,
    tax: 0,
    currency: opts.project?.currency || 'ALL',
    status: 'Draft',
    notes: `Faturë për detyrën "${opts.taskTitle}"${opts.project?.name ? ` (projekti "${opts.project.name}")` : ''}.`,
    invoiceDate: issuedAt,
    dueDate: due,
    taskId: opts.taskId,
    autoGenerated: true,
    createdAt: issuedAt,
    updatedAt: issuedAt,
  }));
  await addDoc(collection(db, 'invoiceItems'), stripUndefined({
    invoiceId: invoiceRef.id,
    description: opts.taskTitle,
    quantity: 1,
    unitPrice: opts.value,
    totalPrice: opts.value,
    teamId,
    businessId,
    customerId: opts.project?.customerId,
    createdAt: issuedAt,
    updatedAt: issuedAt,
  }));

  if (decision.applyToBudget && opts.project?.id) {
    // increment() is atomic — two tasks added at once both land, which a
    // read-then-write of `project.budget` would silently lose.
    await updateDoc(doc(db, 'projects', opts.project.id), { budget: increment(opts.value), updatedAt: new Date() });
  }
  // Mark it counted so a later backfill can't add the same value twice. A
  // recurring project's task counts as "applied" too: its draft invoice IS the
  // billing artefact, and the backfill must never push it into the fee.
  await updateDoc(doc(db, 'tasks', opts.taskId), { valueAppliedToBudget: true, updatedAt: new Date() });

  return { invoiceNumber, appliedToBudget: decision.applyToBudget, skipped: false };
}

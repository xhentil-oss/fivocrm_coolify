// Recurring INVOICES (a user-created recurring invoice spawning occurrences) —
// which period an occurrence belongs to, when the next one is due, and whether
// this series may bill right now.
//
// Background (audit Aug 2026, `workspace/INVOICES_AUDIT_2026_08.md`): this engine
// was the last one still using a TIMESTAMP as its idempotency token, years after
// `recurringBilling.ts` (projects) and `recurringExpenses.ts` moved to a period
// key. The guard in `api/cron/run.ts` read:
//
//     if (lastChildCreatedAt >= nextRecurringDate) skip
//
// The first catch-up child is created "now", which is newer than every remaining
// past due date — so once a series lagged a single cycle (cron downtime, the
// Vercel→VPS move, a back-dated start) the guard stayed true FOREVER and the
// retainer silently stopped billing. No error, no notification, just missing
// revenue.
//
// Two more faults came with it:
//   · `defaultNextRecurring()` in InvoicesView used `setMonth(+1)` on the due
//     date, so a 31 Jan retainer next billed on 3 March — February gone for good.
//   · nothing stopped an invoice-driven series and a project-driven series from
//     billing the same retainer twice (`scripts/stop-duplicate-invoice-engines.mjs`
//     existed purely to clean that up by hand).
//
// Everything that decides "which period is this, and may it bill" now lives here,
// is unit-tested, and is MIRRORED by `invoiceBillingPeriodKey` /
// `invoiceBillingBlockReason` in `api/cron/run.ts` — keep the two in sync.

import { startOfBillingWeek } from './recurringBilling';
import { addMonthsClamped } from './recurringExpenses';
// Calendar questions are answered in ONE declared zone — see recurringUtils.
import { zonedParts, addZonedDays, zonedDate, daysInZonedMonth } from '../recurringUtils';

export type InvoiceFrequency = 'weekly' | 'monthly' | 'quarterly' | 'yearly';

export const SUPPORTED_INVOICE_FREQUENCIES: ReadonlyArray<InvoiceFrequency> =
  ['weekly', 'monthly', 'quarterly', 'yearly'];

export type InvoiceGenerationBlock =
  | 'not-recurring'
  | 'auto-generated'
  | 'parent-cancelled'
  | 'parent-draft'
  | 'paused'
  | 'unsupported-frequency'
  | 'no-next-date'
  | 'not-due'
  | 'series-ended'
  | 'already-generated'
  | 'project-also-bills';

/** Blocks that can never clear on their own — the series should be switched off. */
export const PERMANENT_INVOICE_BLOCKS: ReadonlyArray<InvoiceGenerationBlock> =
  ['series-ended', 'project-also-bills', 'parent-cancelled'];


/**
 * Last instant (business zone) of the calendar day `end` falls on. "Përsërit
 * deri më 31 mars" includes the 31st: the picker stores local 00:00 of that
 * day, so a bare `billingDate > endDate` dropped the end day's own occurrence.
 */
export function endOfSeriesEndDay(end: Date): Date {
  const p = zonedParts(end);
  return zonedDate(p.year, p.month, p.day, 23, 59, 59, 999);
}

/** Minimal shape this engine needs — deliberately not the full `Invoice` type, so
 *  the server mirror can pass a raw Firestore document. */
export interface RecurringInvoiceLike {
  /** The parent's own status: a Cancelled parent never bills, a Draft one waits. */
  status?: string | null;
  isRecurring?: boolean;
  isRecurringPaused?: boolean;
  autoGenerated?: boolean;
  recurringFrequency?: string;
  nextRecurringDate?: unknown;
  recurringEndDate?: unknown;
  /** Period key of the last occurrence this series generated — the idempotency token. */
  lastGeneratedPeriodKey?: string | null;
  /**
   * Day-of-month the series bills on, fixed for the life of the series.
   *
   * Without it the next due date was computed from `nextRecurringDate.getDate()`,
   * i.e. from the PREVIOUS occurrence — which is already clamped. A 31 Jan
   * retainer therefore went 31 Jan → 28 Feb → 28 Mar → 28 Apr … and never
   * returned to the 31st: one clamp in February silently re-anchored the whole
   * series three days early, forever. This is the same drift
   * `recurringAnchorDay` prevents for recurring expenses.
   */
  recurringAnchorDay?: number | null;
}

/** Firestore Timestamp | Date | ISO string | millis → Date, or null. */
export function toDateOrNull(value: unknown): Date | null {
  if (!value) return null;
  if (value instanceof Date) return isNaN(value.getTime()) ? null : value;
  const v = value as any;
  if (typeof v.toDate === 'function') {
    const d = v.toDate();
    return d instanceof Date && !isNaN(d.getTime()) ? d : null;
  }
  const secs = typeof v.seconds === 'number' ? v.seconds
    : (typeof v._seconds === 'number' ? v._seconds : null);
  if (secs != null) return new Date(secs * 1000);
  const d = new Date(value as any);
  return isNaN(d.getTime()) ? null : d;
}

const p2 = (n: number) => String(n).padStart(2, '0');

/**
 * Stable key for the billing period `at` falls in. Exactly one occurrence may
 * exist per (parent invoice, key) — this is the idempotency token.
 *
 *   weekly    → 'W2026-08-17'  (Monday of that week)
 *   monthly   → '2026-08'
 *   quarterly → 'Q2026-3'
 *   yearly    → 'Y2026'
 */
export function invoiceBillingPeriodKey(frequency: string, at: Date): string {
  if (frequency === 'weekly') {
    const m = zonedParts(startOfBillingWeek(at));
    return `W${m.year}-${p2(m.month + 1)}-${p2(m.day)}`;
  }
  const at_ = zonedParts(at);
  if (frequency === 'quarterly') {
    return `Q${at_.year}-${Math.floor(at_.month / 3) + 1}`;
  }
  if (frequency === 'yearly') {
    return `Y${at_.year}`;
  }
  return `${at_.year}-${p2(at_.month + 1)}`;
}

/**
 * The day-of-month this series bills on: the stored anchor when the series has
 * one, else the day of the occurrence we are advancing from.
 *
 * NEVER derive it from the occurrence when an anchor exists, and never write it
 * back from a clamped date — that is exactly how a 31st series degrades to the
 * 28th (see `recurringAnchorDay`).
 */
export function resolveInvoiceAnchorDay(
  invoice: Pick<RecurringInvoiceLike, 'recurringAnchorDay'>,
  scheduled: Date,
): number {
  const raw = invoice.recurringAnchorDay;
  // `Number(raw)` rather than a `typeof` test: the cron mirror has always
  // coerced, so a legacy anchor stored as the string "31" made the two engines
  // compute different due dates for the same series.
  const n = raw == null || (raw as unknown) === '' ? NaN : Math.round(Number(raw));
  if (Number.isFinite(n) && n >= 1 && n <= 31) return n;
  return zonedParts(scheduled).day;
}

/**
 * The due date one full cycle after `from`, preserving the day-of-month and
 * clamping (never `setMonth(+1)`, which overflows a 31st into the month after
 * next and silently skips a month).
 */
export function nextInvoiceOccurrence(from: Date, frequency: string, anchorDay?: number): Date {
  if (frequency === 'weekly') return addZonedDays(from, 7);
  if (frequency === 'yearly') {
    // Feb 29 → Feb 28 in a non-leap year, rather than 1 March.
    return addMonthsClamped(from, 12, anchorDay);
  }
  if (frequency === 'quarterly') return addMonthsClamped(from, 3, anchorDay);
  return addMonthsClamped(from, 1, anchorDay);
}

/**
 * The date the occurrence should be BILLED on.
 *
 * The scheduled date wins while it is still inside the current period (the cron
 * ran a few hours or days late — the invoice belongs to its planned schedule).
 * Once the series has lagged whole periods, we bill the CURRENT period instead:
 * back-dating an invoice into a closed month rewrites books that are already
 * reported, and emailing a client six back-dated invoices at once is worse than
 * missing them. The skipped periods are surfaced, never silently backfilled.
 */
export function billingDateFor(scheduled: Date, frequency: string, now: Date): Date {
  return invoiceBillingPeriodKey(frequency, scheduled) === invoiceBillingPeriodKey(frequency, now)
    ? scheduled
    : now;
}

/**
 * How many whole periods this series fell behind (0 when on schedule). Recorded on
 * the parent so the UI can say "3 periudha u kapërcyen" instead of the owner
 * discovering the gap in an annual report.
 */
export function periodsSkipped(
  scheduled: Date,
  frequency: string,
  now: Date,
  anchorDay?: number,
): number {
  if (scheduled >= now) return 0;
  let count = 0;
  let cursor = new Date(scheduled);
  const anchor = anchorDay ?? zonedParts(scheduled).day;
  const nowKey = invoiceBillingPeriodKey(frequency, now);
  // Bounded: a decade of weeks is the worst realistic drift, and the loop must
  // never be able to hang the cron on corrupt data.
  while (invoiceBillingPeriodKey(frequency, cursor) !== nowKey && count < 600) {
    cursor = nextInvoiceOccurrence(cursor, frequency, anchor);
    count++;
  }
  return Math.max(0, count - 1);
}

/**
 * Document id of the occurrence covering `periodKey` of a series.
 *
 * Deterministic ON PURPOSE, and mirrored in `api/cron/run.ts`. The period key was
 * already the idempotency token, but it was only ever CHECKED: the occurrence went
 * to a random id and the parent's claim was a separate, unordered write. If that
 * claim failed — or the run died between the two, or a manual trigger raced the
 * scheduled cron — the next pass billed the period again and emailed the client a
 * second invoice. With the key IN the id, a `create()` makes the duplicate
 * impossible instead of merely unlikely.
 *
 * `prefix` separates the two engines: 'rec' = invoice-driven (parent = invoice id),
 * 'auto' = project-driven (parent = project id).
 */
export function recurringOccurrenceId(
  prefix: 'rec' | 'auto',
  parentId: string,
  periodKey: string,
): string {
  return `${prefix}_${parentId}_${periodKey}`;
}

/** A linked project that bills its OWN fee on a cycle — the other engine. */
export interface BillingProjectLike {
  isRecurring?: boolean;
  isRecurringPaused?: boolean;
  status?: string;
  billingType?: string;
}

/**
 * True when the linked project's own recurrence would bill this retainer as well.
 * Two engines must never overlap: `recurring-invoices` Part 1 drives user-created
 * recurring INVOICES, Part 2 drives recurring PROJECTS. A project-linked recurring
 * invoice is the one shape where both fire for the same money.
 *
 * A paused or terminal project is not billing, so it does not block.
 */
export function projectAlsoBills(project: BillingProjectLike | null | undefined): boolean {
  if (!project?.isRecurring) return false;
  if (project.isRecurringPaused) return false;
  if (project.billingType === 'one-time') return false;
  if (project.status === 'Cancelled' || project.status === 'Archived') return false;
  return true;
}

/**
 * Why this recurring invoice may not generate an occurrence for the period
 * containing `now`, or `null` when it is due.
 *
 * `project` is the invoice's linked project when it has one (pass null/undefined
 * otherwise) — it is what closes the double-billing overlap.
 */
export function invoiceBillingBlockReason(
  invoice: RecurringInvoiceLike,
  now: Date,
  project?: BillingProjectLike | null,
): InvoiceGenerationBlock | null {
  if (!invoice.isRecurring) return 'not-recurring';
  // Children never recurse — only the parent original drives the cycle.
  if (invoice.autoGenerated) return 'auto-generated';
  // A cancelled parent is a withdrawn contract: it must neither bill nor email
  // the client again. Permanent — the series is switched off. A Draft parent
  // has not been issued yet, so it waits (not permanent: issuing it resumes).
  if (invoice.status === 'Cancelled') return 'parent-cancelled';
  if (invoice.status === 'Draft') return 'parent-draft';

  const frequency = invoice.recurringFrequency;
  if (!frequency || !SUPPORTED_INVOICE_FREQUENCIES.includes(frequency as InvoiceFrequency)) {
    return 'unsupported-frequency';
  }
  // Checked before `paused` so an overlap is reported (and switched off) even on a
  // paused series — resuming it later must not quietly resume the double bill.
  if (projectAlsoBills(project)) return 'project-also-bills';
  if (invoice.isRecurringPaused) return 'paused';

  const scheduled = toDateOrNull(invoice.nextRecurringDate);
  if (!scheduled) return 'no-next-date';
  if (scheduled > now) return 'not-due';

  const billingDate = billingDateFor(scheduled, frequency, now);

  const endDate = toDateOrNull(invoice.recurringEndDate);
  if (endDate && billingDate > endOfSeriesEndDay(endDate)) return 'series-ended';

  if (invoice.lastGeneratedPeriodKey
      && invoice.lastGeneratedPeriodKey === invoiceBillingPeriodKey(frequency, billingDate)) {
    return 'already-generated';
  }

  return null;
}

/**
 * Back-compat for parents that predate `lastGeneratedPeriodKey`: derive whether the
 * period is already covered from the occurrences that exist. Without this the first
 * run after deploy would bill every live series a second time.
 *
 * `children` are the auto-generated occurrences of this parent; each contributes its
 * own `periodKey` when it has one, else the period of its invoice date.
 */
export function periodAlreadyCovered(
  frequency: string,
  periodKey: string,
  children: Array<{ periodKey?: string | null; invoiceDate?: unknown; createdAt?: unknown }>,
): boolean {
  return children.some(child => {
    if (child.periodKey) return child.periodKey === periodKey;
    const d = toDateOrNull(child.invoiceDate) || toDateOrNull(child.createdAt);
    return !!d && invoiceBillingPeriodKey(frequency, d) === periodKey;
  });
}

// ── Series schedule: anchor + next date, as the FORM resolves them ──────────

export interface RecurringScheduleInput {
  frequency: string;
  /** The invoice's own date — the series anchor. */
  invoiceDate: Date;
  /**
   * The next date the USER picked in the form, ONLY when they touched the
   * picker. A date the form pre-filled (the due date, a stored value shown
   * back) is not a pick and must be passed as `null`.
   */
  pickedNext?: Date | null;
  /** The series' stored anchor day (edit only). */
  storedAnchorDay?: number | string | null;
  /** The series' stored next date (edit only). */
  storedNext?: Date | null;
}

/**
 * The anchor day and the next occurrence a recurring invoice is saved with.
 *
 * Precedence (see InvoicesView):
 *   1. a date the user explicitly picked wins for both — that is intent, and
 *      it is how a series the cron clamped to the 28th gets back to the 31st;
 *   2. otherwise the stored anchor (never re-derived on an unrelated edit) and
 *      the stored next date;
 *   3. otherwise the INVOICE DATE's own day and one full cycle after it.
 *
 * Rung 2 used to fire for a date the form itself had filled in: ticking
 * "Faturë periodike" copied the DUE date into the picker, the submit then read
 * it as a pick, and a net-30 invoice dated 31 January was born anchored on the
 * 2nd with its next occurrence on 2 March — February never billed. The due
 * date is a payment TERM, not the billing cycle.
 */
export function resolveRecurringSchedule(input: RecurringScheduleInput): {
  anchorDay: number;
  nextRecurringDate: Date;
} {
  const { frequency, invoiceDate, pickedNext, storedNext } = input;
  if (pickedNext) {
    return { anchorDay: zonedParts(pickedNext).day, nextRecurringDate: pickedNext };
  }
  const anchorDay = resolveInvoiceAnchorDay({ recurringAnchorDay: input.storedAnchorDay as any }, invoiceDate);
  return {
    anchorDay,
    nextRecurringDate: storedNext ?? nextInvoiceOccurrence(invoiceDate, frequency, anchorDay),
  };
}

// ── Resuming a paused / stopped series ──────────────────────────────────────

/** First instant (business zone) of the period `at` falls in. */
export function invoicePeriodStart(frequency: string, at: Date): Date {
  if (frequency === 'weekly') return startOfBillingWeek(at);
  const p = zonedParts(at);
  if (frequency === 'quarterly') return zonedDate(p.year, Math.floor(p.month / 3) * 3, 1);
  if (frequency === 'yearly') return zonedDate(p.year, 0, 1);
  return zonedDate(p.year, p.month, 1);
}

/** Start of the period immediately before the one `at` falls in. */
export function previousInvoicePeriodStart(frequency: string, at: Date): Date {
  if (frequency === 'weekly') return addZonedDays(startOfBillingWeek(at), -7);
  const p = zonedParts(at);
  // The 1st, so stepping back from the 31st cannot skip a short month.
  if (frequency === 'quarterly') return zonedDate(p.year, Math.floor(p.month / 3) * 3 - 3, 1);
  if (frequency === 'yearly') return zonedDate(p.year - 1, 0, 1);
  return zonedDate(p.year, p.month - 1, 1);
}

/**
 * The first occurrence of the series that falls in the period containing `at`
 * or later, keeping the anchor.
 *
 * `from` is the series' current next date: when it is already in the current
 * period (or ahead of it) it is returned unchanged; when it lags whole periods
 * it is walked forward with `nextInvoiceOccurrence` (anchor preserved, so a 31st
 * series lands on the 31st again). Without a `from` the occurrence is seeded on
 * the anchor day of the current month (noon, business zone).
 */
export function nextOccurrenceInOrAfterPeriod(
  frequency: string,
  at: Date,
  from: Date | null | undefined,
  anchorDay?: number,
): Date {
  const periodStart = invoicePeriodStart(frequency, at);
  if (from) {
    if (from >= periodStart) return from;
    let cursor = from;
    let guard = 0;
    while (cursor < periodStart && guard < 600) {
      cursor = nextInvoiceOccurrence(cursor, frequency, anchorDay);
      guard++;
    }
    return cursor;
  }
  if (frequency === 'weekly') return at;
  const p = zonedParts(at);
  const day = anchorDay ?? p.day;
  return zonedDate(p.year, p.month, Math.min(day, daysInZonedMonth(p.year, p.month)), 12);
}

/**
 * Re-point a stale claim and next date so RESUMING a series raises no false
 * "N periudha pa faturë" alarm and bills the current period exactly once.
 *
 * Mirrors `resumedBillingClaimPatch` in projectArchive.ts. A series paused in
 * March and resumed in September still carries `nextRecurringDate` = April and
 * a March claim; the first run after the resume would then report five skipped
 * periods and notify the owner about months that were deliberately NOT billed.
 * (Re-enabling a STOPPED series is worse: the stop nulls the next date and the
 * form re-seeds it from the invoice date — possibly a year back.)
 *
 *   · the claim moves to the PREVIOUS period, unless it already is the previous
 *     or the current one (then there is no gap to hide, and moving it back could
 *     re-open a period that was invoiced); a series with no claim gets none
 *     invented — the cron's `periodAlreadyCovered` back-compat handles it;
 *   · the next date moves to the first occurrence in the current period (or the
 *     NEXT one, when the current period is already claimed), keeping the anchor.
 *
 * Returns only the fields that actually change.
 */
export function resumedInvoiceClaimPatch(
  invoice: RecurringInvoiceLike,
  at: Date = new Date(),
): Record<string, unknown> {
  const frequency = invoice.recurringFrequency || 'monthly';
  if (!SUPPORTED_INVOICE_FREQUENCIES.includes(frequency as InvoiceFrequency)) return {};

  const scheduled = toDateOrNull(invoice.nextRecurringDate);
  const anchorDay = resolveInvoiceAnchorDay(invoice, scheduled ?? at);
  const currentKey = invoiceBillingPeriodKey(frequency, at);
  const previousKey = invoiceBillingPeriodKey(frequency, previousInvoicePeriodStart(frequency, at));
  const claim = invoice.lastGeneratedPeriodKey || null;

  const patch: Record<string, unknown> = {};
  let effectiveClaim = claim;
  if (claim && claim !== currentKey && claim !== previousKey) {
    patch.lastGeneratedPeriodKey = previousKey;
    effectiveClaim = previousKey;
  }

  let next = nextOccurrenceInOrAfterPeriod(frequency, at, scheduled, anchorDay);
  if (effectiveClaim === currentKey && invoiceBillingPeriodKey(frequency, next) === currentKey) {
    next = nextInvoiceOccurrence(next, frequency, anchorDay);
  }
  if (!scheduled || next.getTime() !== scheduled.getTime()) patch.nextRecurringDate = next;
  return patch;
}

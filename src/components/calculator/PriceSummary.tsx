/* ═══════════════════════════════════════════════════════════════════════
   Price Summary — Sticky right panel with live breakdown
   ═══════════════════════════════════════════════════════════════════════ */

import React, { useRef } from 'react';
import { Badge } from '../ui/badge';
import { Separator } from '../ui/separator';
import {
  FileText, Printer, RotateCcw, ChevronDown, ChevronUp,
} from 'lucide-react';
import type { CalculationResult, Currency, CalculatorSelections } from '../../lib/calculator/types';
import { formatCurrency } from '../../lib/calculator/calculations';

interface Props {
  result: CalculationResult;
  currency: Currency;
  sel: CalculatorSelections;
  onReset: () => void;
  onSaveQuote: () => void;
}

export default function PriceSummary({ result, currency, sel, onReset, onSaveQuote }: Props) {
  const [expandedCats, setExpandedCats] = React.useState<Set<string>>(new Set());
  const printRef = useRef<HTMLDivElement>(null);

  const toggleCat = (cat: string) => {
    setExpandedCats(prev => {
      const next = new Set(prev);
      next.has(cat) ? next.delete(cat) : next.add(cat);
      return next;
    });
  };

  const handlePrint = () => {
    const el = printRef.current;
    if (!el) return;
    const w = window.open('', '_blank');
    if (!w) return;
    w.document.write(`
      <html><head><title>Quote — FivoCRM Calculator</title>
      <style>
        body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; padding: 40px; color: #1a1a1a; max-width: 700px; margin: 0 auto; }
        h2 { margin: 0 0 4px; font-size: 22px; }
        .badge { display: inline-block; background: #f0fdf4; color: #16a34a; padding: 2px 10px; border-radius: 12px; font-size: 12px; font-weight: 600; }
        .section { margin: 16px 0; }
        .section-header { font-weight: 600; font-size: 14px; color: #374151; margin-bottom: 6px; }
        .line { display: flex; justify-content: space-between; font-size: 13px; padding: 3px 0; }
        .line-label { color: #6b7280; }
        .line-amount { font-weight: 500; }
        .total-row { display: flex; justify-content: space-between; font-size: 16px; font-weight: 700; padding: 8px 0; border-top: 2px solid #e5e7eb; margin-top: 8px; }
        .discount { color: #dc2626; }
        hr { border: none; border-top: 1px solid #e5e7eb; margin: 12px 0; }
        .footer { margin-top: 24px; font-size: 11px; color: #9ca3af; }
      </style></head><body>
      ${el.innerHTML}
      <div class="footer">Generated by FivoCRM Price Calculator — ${new Date().toLocaleDateString()}</div>
      </body></html>
    `);
    w.document.close();
    w.print();
  };

  const fc = (n: number) => formatCurrency(n, currency);
  const hasItems = result.categories.length > 0;

  return (
    <div className="bg-white rounded-xl border border-gray-200 shadow-sm overflow-hidden">
      {/* Header */}
      <div className="px-5 py-4 bg-gradient-to-r from-gray-900 to-gray-800 text-white">
        <div className="flex items-center justify-between">
          <div>
            <p className="text-xs text-gray-400 uppercase tracking-wider font-medium">Përmbledhja e çmimit</p>
            <h2 className="text-lg font-bold mt-0.5">
              {hasItems ? result.suggestedLabel + ' Package' : 'Asgjë e zgjedhur'}
            </h2>
          </div>
          {hasItems && (
            <Badge variant="outline" className="border-emerald-500/40 text-emerald-400 text-xs">
              {result.enabledServicesCount} shërbime
            </Badge>
          )}
        </div>
      </div>

      <div ref={printRef}>
        {/* Categories breakdown */}
        {hasItems ? (
          <div className="px-5 py-3 space-y-1 max-h-[50vh] overflow-y-auto">
            {result.categories.map(cat => {
              const expanded = expandedCats.has(cat.category);
              return (
                <div key={cat.category} className="border-b border-gray-100 last:border-0 pb-2">
                  <button
                    onClick={() => toggleCat(cat.category)}
                    className="w-full flex items-center justify-between py-2 text-sm hover:bg-gray-50 rounded -mx-1 px-1 transition-colors"
                  >
                    <span className="font-medium text-gray-800">{cat.category}</span>
                    <div className="flex items-center gap-3">
                      <span className="text-gray-600 font-medium text-xs tabular-nums">
                        {cat.oneTime > 0 && fc(cat.oneTime)}
                        {cat.oneTime > 0 && cat.monthly > 0 && ' + '}
                        {cat.monthly > 0 && `${fc(cat.monthly)}/muaj`}
                      </span>
                      {expanded ? <ChevronUp className="w-3.5 h-3.5 text-gray-400" /> : <ChevronDown className="w-3.5 h-3.5 text-gray-400" />}
                    </div>
                  </button>
                  {expanded && (
                    <div className="pl-2 pb-2 space-y-1 animate-in fade-in slide-in-from-top-1 duration-150">
                      {cat.items.map((item, i) => (
                        <div key={i} className="flex items-center justify-between text-xs text-gray-500 py-0.5">
                          <span>
                            {item.label}
                            {item.quantity != null && item.unitPrice != null && (
                              <span className="text-gray-400 ml-1">({item.quantity} × {fc(item.unitPrice)})</span>
                            )}
                          </span>
                          <span className="tabular-nums font-medium text-gray-600">
                            {fc(item.amount)}
                            {item.type === 'monthly' && <span className="text-gray-400">/muaj</span>}
                          </span>
                        </div>
                      ))}
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        ) : (
          <div className="px-5 py-10 text-center text-sm text-gray-400">
            Aktivizo shërbime në anën e majtë për të parë çmimet
          </div>
        )}

        {/* Totals */}
        {hasItems && (
          <div className="px-5 py-4 bg-gray-50 border-t border-gray-200 space-y-2">
            <div className="flex justify-between text-sm">
              <span className="text-gray-500">One-time subtotal</span>
              <span className="font-medium tabular-nums">{fc(result.subtotalOneTime)}</span>
            </div>
            <div className="flex justify-between text-sm">
              <span className="text-gray-500">Monthly subtotal</span>
              <span className="font-medium tabular-nums">{fc(result.subtotalMonthly)}/muaj</span>
            </div>

            {result.bundleDiscountAmount > 0 && (
              <div className="flex justify-between text-sm text-green-600">
                <span>Bundle: {result.bundleDiscountLabel}</span>
                <span className="font-medium tabular-nums">−{fc(result.bundleDiscountAmount)}</span>
              </div>
            )}
            {result.manualDiscountAmount > 0 && (
              <div className="flex justify-between text-sm text-green-600">
                <span>Zbritje manuale</span>
                <span className="font-medium tabular-nums">−{fc(result.manualDiscountAmount)}</span>
              </div>
            )}

            <Separator />

            <div className="flex justify-between text-sm font-semibold">
              <span>Total one-time</span>
              <span className="tabular-nums">{fc(result.totalOneTime)}</span>
            </div>
            <div className="flex justify-between text-sm font-semibold">
              <span>Total mujor</span>
              <span className="tabular-nums">{fc(result.totalMonthly)}/muaj</span>
            </div>

            <Separator />

            <div className="flex justify-between items-baseline">
              <span className="text-base font-bold text-gray-900">Grand Total (muaji 1)</span>
              <span className="text-xl font-bold text-gray-900 tabular-nums">{fc(result.grandTotal)}</span>
            </div>

            {/* Internal costs (optional) */}
            {result.internalCostOneTime != null && (
              <div className="mt-3 pt-3 border-t border-dashed border-gray-300 space-y-1">
                <p className="text-xs font-semibold text-gray-400 uppercase tracking-wider">Internal</p>
                <div className="flex justify-between text-xs text-gray-400">
                  <span>Kosto interne</span>
                  <span className="tabular-nums">{fc(result.internalCostOneTime! + result.internalCostMonthly!)}</span>
                </div>
                {result.profitMarginPercent != null && (
                  <div className="flex justify-between text-xs">
                    <span className="text-gray-400">Marxh fitimi</span>
                    <span className={`font-medium tabular-nums ${result.profitMarginPercent > 30 ? 'text-green-600' : 'text-amber-600'}`}>
                      {result.profitMarginPercent.toFixed(1)}%
                    </span>
                  </div>
                )}
                {result.minimumAcceptablePrice != null && (
                  <div className="flex justify-between text-xs text-gray-400">
                    <span>Çmim minimal</span>
                    <span className="tabular-nums">{fc(result.minimumAcceptablePrice)}</span>
                  </div>
                )}
              </div>
            )}
          </div>
        )}
      </div>

      {/* Discount inputs */}
      {hasItems && (
        <div className="px-5 py-3 border-t border-gray-100">
          <p className="text-xs font-semibold text-gray-400 uppercase tracking-wider mb-2">Zbritje</p>
          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className="text-xs text-gray-500 mb-1 block">Discount %</label>
              <input
                type="number"
                min={0}
                max={100}
                value={sel.discountPercent || ''}
                onChange={() => {}}
                className="w-full h-8 rounded-md border border-gray-200 px-2 text-sm"
                readOnly
              />
            </div>
            <div>
              <label className="text-xs text-gray-500 mb-1 block">Fixed discount</label>
              <input
                type="number"
                min={0}
                value={sel.discountFixed || ''}
                onChange={() => {}}
                className="w-full h-8 rounded-md border border-gray-200 px-2 text-sm"
                readOnly
              />
            </div>
          </div>
          <p className="text-[10px] text-gray-400 mt-1">Kontrollohen nga paneli i konfigurimit</p>
        </div>
      )}

      {/* Actions */}
      <div className="px-5 py-4 border-t border-gray-100 space-y-2">
        <button
          onClick={onSaveQuote}
          disabled={!hasItems}
          className="w-full flex items-center justify-center gap-2 py-2.5 rounded-lg bg-gray-900 text-white text-sm font-semibold hover:bg-gray-800 disabled:opacity-40 disabled:cursor-not-allowed transition-colors"
        >
          <FileText className="w-4 h-4" />
          Save Quote
        </button>
        <div className="grid grid-cols-2 gap-2">
          <button
            onClick={handlePrint}
            disabled={!hasItems}
            className="flex items-center justify-center gap-1.5 py-2 rounded-lg border border-gray-200 text-sm font-medium text-gray-700 hover:bg-gray-50 disabled:opacity-40 disabled:cursor-not-allowed transition-colors"
          >
            <Printer className="w-3.5 h-3.5" />
            Print / PDF
          </button>
          <button
            onClick={onReset}
            className="flex items-center justify-center gap-1.5 py-2 rounded-lg border border-gray-200 text-sm font-medium text-gray-700 hover:bg-gray-50 transition-colors"
          >
            <RotateCcw className="w-3.5 h-3.5" />
            Reset
          </button>
        </div>
      </div>
    </div>
  );
}
